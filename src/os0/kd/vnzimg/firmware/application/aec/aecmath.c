/* floor(sqrt(value)), by bisection on twice the root */
uint16_t aecSqrt(uint32_t value)
{
	uint32_t root = 0x10000, bit = 0x8000, half = root;

	for (;;) {
		half >>= 1;
		half *= half;
		if (half < value)
			root += bit;
		else if (value < half)
			root -= bit;
		bit >>= 1;
		if (!bit)
			break;
		half = root;
	}
	return root >> 1;
}

/* log2 of a 15-bit value, Q12; 0 and 1 (and negatives) give the table's first */
uint16_t aecLog2Fraction(int16_t value)
{
	uint32_t index = 0, base = 0;
	int32_t bit;

	if (!(value & 0x8000)) {
		for (bit = 14; bit >= 1; bit--) {
			if (value & (1 << bit))
				break;
		}
		if (bit >= 1) {
			base = bit << 12;
			if (bit >= 9)
				index = (value >> (bit - 9)) & 0x1ff;
			else
				index = (value << (9 - bit)) & 0x1ff;
		}
	}
	return base + log2Table[index];
}

/* 2^(value / 4096) for value < 15 << 12; saturated past it */
int16_t aecExp2Fraction(uint16_t value)
{
	uint16_t fraction = exp2Table[(value >> 3) & 0x1ff] << 4;
	uint32_t whole = value >> 12;

	if (whole >= 15)
		return 32767;
	if (whole == 0)
		return 1;
	return (fraction >> (16 - whole)) + (1 << whole);
}

/* log2, Q12; 0 for negatives */
int32_t aecLog2(int32_t value)
{
	uint8_t shift = 0;

	if (value < 0)
		return 0;
	while (value & 0xffff8000) {
		value >>= 1;
		shift++;
	}
	return (shift << 12) + aecLog2Fraction(value);
}

/* 2^(value / 4096), saturated at 0x7fffffff */
int32_t aecExp2(uint32_t value)
{
	uint32_t shift = value >> 12;
	int32_t fraction;

	if (shift < 15)
		shift = 0;
	else
		shift -= 14;
	fraction = aecExp2Fraction(value - (shift << 12));
	if (shift < 15)
		return fraction << shift;
	return 0x7fffffff;
}

/*
 * log2 of a 64-bit value, Q12, shifting it down in place. Sony's loop
 * tests only the low word's bits 15-31 (the mask is not sign extended);
 * kept as it is.
 */
int32_t aecLog2Long(uint64_t *value)
{
	uint8_t shift = 0;

	if (*value < 1)
		return 0;
	while (*value & 0xffff8000u) {
		shift++;
		*value >>= 1;
	}
	return (shift << 12) + aecLog2Fraction((int16_t)*value);
}
