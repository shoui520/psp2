static int32_t add(int32_t a, int32_t b)
{
	return (int32_t)((uint32_t)a + (uint32_t)b);
}

static int32_t subtract(int32_t a, int32_t b)
{
	return (int32_t)((uint32_t)a - (uint32_t)b);
}

/* (re + i im)(c + i s), Q23 */
static AecComplex rotate(int32_t re, int32_t im, int32_t c, int32_t s)
{
	AecComplex result;

	result.re = (int32_t)(((int64_t)re * c - (int64_t)im * s) >> TWIDDLE_BITS);
	result.im = (int32_t)(((int64_t)re * s + (int64_t)im * c) >> TWIDDLE_BITS);
	return result;
}

static void butterfly(AecComplex *z, int32_t i0, int32_t quarter, int32_t c1, int32_t s1,
	int32_t c3, int32_t s3, uint32_t inverse)
{
	int32_t i1 = i0 + quarter, i2 = i1 + quarter, i3 = i2 + quarter;
	AecComplex a, b, plus, minus;

	a.re = subtract(z[i0].re, z[i2].re);
	a.im = subtract(z[i0].im, z[i2].im);
	b.re = subtract(z[i1].re, z[i3].re);
	b.im = subtract(z[i1].im, z[i3].im);
	z[i0].re = add(z[i0].re, z[i2].re);
	z[i0].im = add(z[i0].im, z[i2].im);
	z[i1].re = add(z[i1].re, z[i3].re);
	z[i1].im = add(z[i1].im, z[i3].im);

	/* a - i b and a + i b */
	minus.re = add(a.re, b.im);
	minus.im = subtract(a.im, b.re);
	plus.re = subtract(a.re, b.im);
	plus.im = add(a.im, b.re);
	if (inverse) {
		z[i2] = rotate(plus.re, plus.im, c1, s1);
		z[i3] = rotate(minus.re, minus.im, c3, s3);
	} else {
		z[i2] = rotate(minus.re, minus.im, c1, s1);
		z[i3] = rotate(plus.re, plus.im, c3, s3);
	}
}

void aecFft(uint32_t mode, AecComplex *z, uint32_t inverse)
{
	int32_t length, stride, j, step, i0, i, k, m;

	(void)mode;
	if (!inverse)
		for (i = 0; i < POINTS; i++) {
			z[i].re = (int32_t)((uint32_t)z[i].re << 7);
			z[i].im = (int32_t)((uint32_t)z[i].im << 7);
		}

	/* the L-shaped stages; e^-i j for the forward transform's W^j */
	for (length = POINTS, stride = 1; length >= 3; length >>= 1, stride <<= 1) {
		int32_t quarter = length >> 2;

		for (j = 0; j < quarter; j++) {
			int32_t t = j * stride, sign = inverse ? -1 : 1;
			int32_t c1 = cosines[t], s1 = sign * cosines[t + QUARTER];
			int32_t c3 = cosines[3 * t], s3 = sign * cosines[3 * t + QUARTER];

			for (step = length; step < POINTS + 1; step <<= 2)
				for (i0 = j - length + step; i0 < POINTS; i0 += 2 * step)
					butterfly(z, i0, quarter, c1, s1, c3, s3, inverse);
		}
	}

	/* the length-2 butterflies */
	for (step = 2; step < POINTS + 1; step <<= 2)
		for (i0 = step - 2; i0 < POINTS; i0 += 2 * step) {
			AecComplex first = z[i0];

			z[i0].re = add(first.re, z[i0 + 1].re);
			z[i0].im = add(first.im, z[i0 + 1].im);
			z[i0 + 1].re = subtract(first.re, z[i0 + 1].re);
			z[i0 + 1].im = subtract(first.im, z[i0 + 1].im);
		}

	/* the bit reversal, counting j in reverse */
	for (i = 1, k = 0; i < POINTS - 1; i++) {
		k ^= POINTS / 2;
		if (k < POINTS / 2) {
			m = POINTS / 2;
			do {
				m >>= 1;
				k ^= m;
			} while (k < m);
		}
		if (i < k) {
			AecComplex swap = z[i];

			z[i] = z[k];
			z[k] = swap;
		}
	}

	for (i = 0; i < POINTS; i++) {
		z[i].re >>= inverse ? 10 : 7;
		z[i].im >>= inverse ? 10 : 7;
	}
}
