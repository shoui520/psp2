static int32_t mulQ27(int32_t a, int32_t b)
{
	return (int32_t)(((int64_t)a * b) >> 27);
}

/* The table index: the mantissa's top bits, the leading one at bit 30 - norm */
static int32_t tableIndex(int32_t mantissa, int32_t norm)
{
	int32_t shift = 21 - norm;

	if (shift > 0)
		return (mantissa >> shift) & 0x1ff;
	return (mantissa << -shift) & 0x1ff;
}

void aacSbrFloatAdd(int32_t am, int8_t ae, int32_t bm, int8_t be,
		    int32_t *mantissa, int8_t *exponent)
{
	int8_t shift = ae - be;
	int32_t sum;

	if (shift > 0) {
		if (shift >= 32)
			shift = 31;
		*exponent = ae;
		bm >>= shift;
	} else {
		shift = -shift;
		if (shift >= 32)
			shift = 31;
		*exponent = be;
		am >>= shift;
	}

	sum = am + bm;
	if (sum >= 0x07ffffff) {
		(*exponent)++;
		sum >>= 1;
	}
	*mantissa = sum;
}

void aacSbrFloatDivide(int32_t am, int8_t ae, int32_t bm, int8_t be,
		       int32_t *mantissa, int8_t *exponent)
{
	int32_t norm = aacSignBits32(bm);
	int32_t index = tableIndex(bm, norm);
	int32_t quotient, shift;

	if (index == 0)
		quotient = am;
	else
		quotient = mulQ27(reciprocal[(index - 1) >> 1], am);

	shift = aacSignBits32(quotient) - 4;
	*mantissa = quotient << shift;
	*exponent = (int8_t)(ae - be + norm - shift - 3);
}

void aacSbrFloatSqrt(int32_t *mantissa, int8_t *exponent)
{
	int32_t value = *mantissa;
	int8_t e = *exponent;
	int32_t norm, index, root;

	if (value < 1) {
		*mantissa = 0;
		*exponent = -28;
		return;
	}

	norm = aacSignBits32(value);
	e = (int8_t)(e - (int8_t)(norm - 4));
	index = tableIndex(value, norm);
	root = index == 0 ? SQRT_HALF : squareRoot[(index - 1) >> 1];

	if (e & 1) {
		root = mulQ27(root, SQRT_HALF);
		e++;
	}
	*mantissa = root;
	*exponent = e >> 1;
}
