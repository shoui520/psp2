unsigned int ToHalfwidth(unsigned int c)
{
	unsigned int result = c;

	if (c >= 0xff00 && c <= 0xffef)
		result = s_halfwidthMap[c - 0xff00];
	if (c == 0x3000)
		return ' ';
	return result;
}
