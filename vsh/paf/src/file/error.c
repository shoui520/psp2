#include "error.h"
#include "../paf_types.h"
#include <kernel/error.h>
#include <sceerror.h>

int32_t ToPafError(int32_t error)
{
	switch (error) {
	case SCE_KERNEL_ERROR_NOT_IMPLEMENTED:
	case SCE_KERNEL_ERROR_UNSUP:
	case SCE_ERROR_ERRNO_EROFS:
		return SCE_PAF_ERROR_FILE_READ_ONLY;
	case SCE_KERNEL_ERROR_INVALID_ARGUMENT:
	case SCE_KERNEL_ERROR_ILLEGAL_ADDR:
	case SCE_KERNEL_ERROR_INVALID_ARGUMENT_SIZE:
	case SCE_KERNEL_ERROR_INVALID_FLAGS:
	case SCE_KERNEL_ERROR_ILLEGAL_SIZE:
	case SCE_KERNEL_ERROR_ILLEGAL_MODE:
	case SCE_ERROR_ERRNO_EFAULT:
	case SCE_ERROR_ERRNO_EINVAL:
		return SCE_PAF_ERROR_FILE_INVALID_ARGUMENT;
	case SCE_KERNEL_ERROR_NO_MEMORY:
	case SCE_ERROR_ERRNO_ENOMEM:
		return SCE_PAF_ERROR_FILE_NO_MEMORY;
	case SCE_ERROR_ERRNO_ENOENT:
		return SCE_PAF_ERROR_FILE_NO_ENTRY;
	case SCE_ERROR_ERRNO_EBADF:
		return SCE_PAF_ERROR_FILE_BAD_FILE;
	case SCE_ERROR_ERRNO_EACCES:
		return SCE_PAF_ERROR_FILE_NO_ACCESS;
	case SCE_ERROR_ERRNO_EBUSY:
		return SCE_PAF_ERROR_FILE_BUSY;
	case SCE_ERROR_ERRNO_EEXIST:
		return SCE_PAF_ERROR_FILE_EXIST;
	case SCE_ERROR_ERRNO_ENODEV:
		return SCE_PAF_ERROR_FILE_NO_DEVICE;
	case SCE_ERROR_ERRNO_EMFILE:
		return SCE_PAF_ERROR_FILE_TOO_MANY;
	case SCE_ERROR_ERRNO_ENOSPC:
		return SCE_PAF_ERROR_FILE_NO_SPACE;
	default:
		return error;
	}
}
