/* a surface's width and height, passed by value (names ours) */
class SurfaceSize {
public:
	__attribute__((always_inline)) SurfaceSize(int32_t width, int32_t height)
		: m_width(width), m_height(height)
	{
	}

	int32_t m_width;
	int32_t m_height;
};

