#!/usr/bin/env python3
"""Generate PSP PRX module info, export tables, and import stubs from module.yml.

Usage:
    mkprx_psp.py <module.yml> -o <output.S>
"""

import argparse
import sys


def _parse_int(val):
	return int(val.strip(), 0)


def _parse_list(val):
	s = val.strip()
	if not (s.startswith("[") and s.endswith("]")):
		raise ValueError(f"expected list, got {val!r}")
	inner = s[1:-1].strip()
	if not inner:
		return []
	return [item.strip().strip('"').strip("'") for item in inner.split(",")]


def parse_module_yml(path):
	"""Parse the declarative YAML subset used by sys661 module.yml files."""
	mod = {
		"name": "",
		"attributes": 0,
		"version": [0, 0],
		"sdk_version": None,
		"sdk_version_sym": "module_sdk_version",
		"stub_order": None,
		"exports": [],
		"imports": [],
	}
	section = None
	cur_lib = None
	sublist = None

	with open(path, "r", encoding="utf-8") as f:
		for lineno, raw in enumerate(f, 1):
			line = raw.split("#", 1)[0].rstrip()
			if not line.strip():
				continue
			indent = len(line) - len(line.lstrip(" "))
			s = line.strip()

			if indent == 0:
				sublist = None
				cur_lib = None
				key, _, val = s.partition(":")
				key = key.strip()
				val = val.strip()
				if key in ("exports", "imports"):
					section = key
					if val == "[]":
						mod[key] = []
				elif key == "name":
					mod["name"] = val.strip('"').strip("'")
				elif key == "attributes":
					mod["attributes"] = _parse_int(val)
				elif key == "version":
					mod["version"] = [_parse_int(x) for x in _parse_list(val)]
				elif key == "sdk_version":
					mod["sdk_version"] = _parse_int(val)
				elif key == "sdk_version_sym":
					mod["sdk_version_sym"] = val.strip('"').strip("'")
				elif key == "stub_order":
					mod["stub_order"] = _parse_list(val)
				else:
					raise ValueError(f"{path}:{lineno}: unknown top-level key {key!r}")
			elif indent == 2 and s.startswith("- "):
				sublist = None
				cur_lib = {
					"name": "",
					"label": None,
					"version": [0, 0],
					"attributes": 0,
					"len": 4 if section == "exports" else 5,
					"pad": None,
					"extra_words": [],
					"bucket_words": [],
					"functions": [],
					"variables": [],
				}
				mod[section].append(cur_lib)
				key, _, val = s[2:].partition(":")
				if key.strip() == "name":
					cur_lib["name"] = val.strip().strip('"').strip("'")
				else:
					raise ValueError(f"{path}:{lineno}: expected '- name:', got {s!r}")
			elif indent == 4 and cur_lib is not None:
				key, _, val = s.partition(":")
				key = key.strip()
				val = val.strip()
				if key in ("functions", "variables"):
					sublist = key
					if val == "[]":
						cur_lib[key] = []
				else:
					sublist = None
					if key == "label":
						cur_lib["label"] = val.strip().strip('"').strip("'")
					elif key == "version":
						cur_lib["version"] = [_parse_int(x) for x in _parse_list(val)]
					elif key == "attributes":
						cur_lib["attributes"] = _parse_int(val)
					elif key == "len":
						cur_lib["len"] = _parse_int(val)
					elif key == "pad":
						cur_lib["pad"] = _parse_int(val)
					elif key == "extra_words":
						cur_lib["extra_words"] = [_parse_int(x) for x in _parse_list(val)]
					elif key == "bucket_words":
						cur_lib["bucket_words"] = [_parse_int(x) for x in _parse_list(val)]
					else:
						raise ValueError(f"{path}:{lineno}: unknown library key {key!r}")
			elif indent == 6 and s.startswith("- ") and cur_lib is not None and sublist is not None:
				sym, _, nid_s = s[2:].partition(":")
				cur_lib[sublist].append((sym.strip(), _parse_int(nid_s)))
			else:
				raise ValueError(f"{path}:{lineno}: unexpected line {raw!r}")

	return mod


def emit_assembly(mod):
	"""Generate PSP PRX import stubs and SCE module/export/import tables."""
	imports = mod["imports"]
	exports = mod["exports"]
	lines = [
		f"/* Generated by tools/mkprx_psp.py for {mod['name']} */",
		"\t.set\tnoreorder",
		"\t.set\tnoat",
		"",
		'\t.section .sceStub.text, "ax", @progbits',
	]

	# Emit import function stubs in stub_order (or import declaration order)
	if mod["stub_order"]:
		imp_by_name = {}
		for idx, im in enumerate(imports):
			imp_by_name.setdefault(im["name"], []).append(im)
		ordered_imps = []
		used = set()
		for name in mod["stub_order"]:
			for im in imp_by_name.get(name, []):
				if id(im) not in used:
					ordered_imps.append(im)
					used.add(id(im))
					break
		for im in imports:
			if id(im) not in used:
				ordered_imps.append(im)
	else:
		ordered_imps = imports

	for im in ordered_imps:
		for sym, nid in im["functions"]:
			lines.append(f"\t.globl\t{sym}")
			lines.append(f"\t.type\t{sym}, @function")
			lines.append(f"{sym}: /* {im['name']} {nid:#010x} */")
			lines.append("\tjr\t$ra")
			lines.append("\tnop")

	lines += [
		"",
		'\t.section .lib.ent.top, "a", @progbits',
		"\t.align\t2",
		"__lib_ent_top:",
		"\t.word\t0",
		"",
		'\t.section .lib.ent, "a", @progbits',
		"\t.align\t2",
	]
	for idx, ex in enumerate(exports):
		if ex.get("label"):
			lines.append(f"\t.globl\t{ex['label']}")
			lines.append(f"{ex['label']}:")
		lib_sym = "0" if ex["name"] == "syslib" else f".L_exp_lib_{idx}"
		lines.append(f"\t.word\t{lib_sym}")
		lines.append(f"\t.byte\t{ex['version'][1]}, {ex['version'][0]}")
		lines.append(f"\t.half\t{ex['attributes']:#06x}")
		lines.append(f"\t.byte\t{ex['len']}, {len(ex['variables'])}")
		lines.append(f"\t.half\t{len(ex['functions'])}")
		lines.append(f"\t.word\t.L_exp_tbl_{idx}")
		for ew in ex["extra_words"]:
			lines.append(f"\t.word\t{ew:#010x}")

	lines += [
		"",
		'\t.section .lib.ent.btm, "a", @progbits',
		"\t.align\t2",
		"__lib_ent_btm:",
		"\t.word\t0",
		"",
		'\t.section .lib.stub.top, "a", @progbits',
		"\t.align\t2",
		"__lib_stub_top:",
		"\t.word\t0",
		"",
		'\t.section .lib.stub, "a", @progbits',
		"\t.align\t2",
	]
	for idx, im in enumerate(imports):
		lines.append(f"\t.word\t.L_imp_lib_{idx}")
		lines.append(f"\t.byte\t{im['version'][1]}, {im['version'][0]}")
		lines.append(f"\t.half\t{im['attributes']:#06x}")
		lines.append(f"\t.byte\t{im['len']}, {len(im['variables'])}")
		lines.append(f"\t.half\t{len(im['functions'])}")
		nid_sym = f".L_imp_nid_{idx}" if im["functions"] else "0"
		stub_sym = im["functions"][0][0] if im["functions"] else "0"
		lines.append(f"\t.word\t{nid_sym}")
		lines.append(f"\t.word\t{stub_sym}")
		if im["len"] >= 6:
			vstub_sym = f".L_imp_vstub_{idx}" if im["variables"] else "0"
			lines.append(f"\t.word\t{vstub_sym}")
		for ew in im["extra_words"]:
			lines.append(f"\t.word\t{ew:#010x}")

	lines += [
		"",
		'\t.section .lib.stub.btm, "a", @progbits',
		"\t.align\t2",
		"__lib_stub_btm:",
		"\t.word\t0",
		"",
		'\t.section .rodata.sceModuleInfo, "a", @progbits',
		"\t.align\t4",
		"\t.globl\tmodule_info",
		"\t.type\tmodule_info, @object",
		"module_info:",
		f"\t.half\t{mod['attributes']:#06x}",
		f"\t.byte\t{mod['version'][1]}, {mod['version'][0]}",
		f'\t.asciz\t"{mod["name"]}"',
		f"\t.space\t{27 - len(mod['name'])}",
		"\t.word\t_gp",
		"\t.word\t__lib_ent_top + 4",
		"\t.word\t__lib_ent_btm",
		"\t.word\t__lib_stub_top + 4",
		"\t.word\t__lib_stub_btm",
		"",
		'\t.section .rodata.sceResident, "a", @progbits',
		"\t.align\t2",
		"\t.word\t0",
	]

	for idx, im in enumerate(imports):
		lines.append(f".L_imp_lib_{idx}:")
		lines.append(f'\t.asciz\t"{im["name"]}"')
		if im["pad"] is not None and im["pad"] > 0:
			lines.append(f"\t.space\t{im['pad']}")
		else:
			lines.append("\t.align\t2")

	for idx, ex in enumerate(exports):
		if ex["name"] != "syslib":
			lines.append(f".L_exp_lib_{idx}:")
			lines.append(f'\t.asciz\t"{ex["name"]}"')
			if ex["pad"] is not None and ex["pad"] > 0:
				lines.append(f"\t.space\t{ex['pad']}")
			else:
				lines.append("\t.align\t2")
		lines.append(f".L_exp_tbl_{idx}:")
		for _, nid in ex["functions"]:
			lines.append(f"\t.word\t{nid:#010x}")
		for _, nid in ex["variables"]:
			lines.append(f"\t.word\t{nid:#010x}")
		for sym, nid in ex["functions"]:
			lines.append(f"\t.word\t{sym} /* {nid:#010x} */")
		for sym, nid in ex["variables"]:
			lines.append(f"\t.word\t{sym} /* {nid:#010x} */")
		for bw in ex["bucket_words"]:
			lines.append(f"\t.word\t{bw:#010x}")

	lines += [
		"",
		'\t.section .rodata.sceNid, "a", @progbits',
		"\t.align\t2",
	]
	for idx, im in enumerate(imports):
		if im["functions"]:
			lines.append(f".L_imp_nid_{idx}:")
			for _, nid in im["functions"]:
				lines.append(f"\t.word\t{nid:#010x}")

	if any(im["variables"] for im in imports):
		lines += [
			"",
			'\t.section .rodata.sceVstub, "a", @progbits',
			"\t.align\t2",
		]
		for idx, im in enumerate(imports):
			if im["variables"]:
				lines.append(f".L_imp_vstub_{idx}:")
				for sym, nid in im["variables"]:
					lines.append(f"\t.globl\t{sym}")
					lines.append(f"{sym}:")
					lines.append("\t.word\t0")
					lines.append(f"\t.word\t{nid:#010x}")

	if mod["sdk_version"] is not None:
		sym = mod["sdk_version_sym"]
		lines += [
			"",
			'\t.section .rodata.sceSdkVersion, "a", @progbits',
			"\t.align\t2",
			f"\t.globl\t{sym}",
			f"\t.type\t{sym}, @object",
			f"{sym}:",
			f"\t.word\t{mod['sdk_version']:#010x}",
		]

	lines.append("")
	return "\n".join(lines)


def main():
	ap = argparse.ArgumentParser(description="Generate PSP PRX tables from module.yml")
	ap.add_argument("input", help="Path to module.yml")
	ap.add_argument("-o", "--output", required=True, help="Output .S path")
	args = ap.parse_args()

	mod = parse_module_yml(args.input)
	asm = emit_assembly(mod)
	with open(args.output, "w", encoding="utf-8") as f:
		f.write(asm)


if __name__ == "__main__":
	main()
