///
/// \mainpage LibVoice
///
///	The LibVoice library provides a C function API for implementing the audio input,
/// output, encoding, decoding, mixing and routing needed for a voice chat application.
///
/// It is composed of two major components: inbound port (IPort) and outbound port
///	(OPort). It provides topology management APIs to build the ports. Each port is
///	created with a specified port type. Based on the port type, it connects the ports
///	and makes voice topology. The application, a libvoice client, writes data to IPorts
///	and reads data from OPorts through LibVoice I/O access APIs. System voice mixes data streams from different IPorts and output the
/// processed data to the connected OPorts. LibVoice also provides APIs for
/// application to update and query the voice topology.
///
///

/// Invalid port ID.
#define SCE_VOICE_INVALID_PORT_ID  0xff
/// The maximum number of \ref SCEVOICE_PORTTYPE_OUT_VOICE ports.
#define SCE_VOICE_MAX_OUT_VOICE_PORT     7
/// The minimum size of memory required by libvoice.
#define SCE_VOICE_MEMORY_CONTAINER_SIZE 0x40000

