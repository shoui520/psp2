#define SCE_VOICE_ERROR_GENERAL                 SCE_ERROR_CAST(0x804e0803)
/// Invalid port.
#define SCE_VOICE_ERROR_PORT_INVALID            SCE_ERROR_CAST(0x804e0804)
/// Invalid argument.
#define SCE_VOICE_ERROR_ARGUMENT_INVALID        SCE_ERROR_CAST(0x804e0805)
/// Invalid container.
