#define SCE_VOICE_ERROR_SERVICE_ATTACHED        SCE_ERROR_CAST(0x804e080b)


/// Port types for libvoice.
/// @see SceVoiceBasePortInfo, SceVoicePortParam
typedef enum SceVoicePortType
{
	/// Null port
	SCEVOICE_PORTTYPE_NULL = -1,
	/// Audio input stream port
	SCEVOICE_PORTTYPE_IN_DEVICE = 0,
	/// PCM input stream port
	SCEVOICE_PORTTYPE_IN_PCMAUDIO = 1,
	/// Voice input stream port
	SCEVOICE_PORTTYPE_IN_VOICE = 2,
	/// PCM output stream port
	SCEVOICE_PORTTYPE_OUT_PCMAUDIO = 3,
	/// Voice output stream port
	SCEVOICE_PORTTYPE_OUT_VOICE = 4,
	/// Audio output stream port
	SCEVOICE_PORTTYPE_OUT_DEVICE = 5
} SceVoicePortType;

/// Enumeration for libvoice port event types.
typedef enum SceVoiceEventType
{
	/// Data is available only for the \ref SCEVOICE_PORTTYPE_OUT_VOICE port
	SCEVOICE_EVENT_DATA_READY = 1 << 0,
	/// <c>AudioInput</c> status, only for the \ref SCEVOICE_PORTTYPE_IN_DEVICE port
	SCEVOICE_EVENT_AUDIOINPUT_STATUS = 1 << 1
} SceVoiceEventType;

/// Enumeration for the state of a port.
/// Each port has its own state.
/// State changes can be the result of events generated by Voice Service,
/// of libvoice function calls made directly by the application, or of the
/// data level of the buffer.
///
/// The following diagram shows how the states change with
/// specific actions or events on the port:
///
/// @code
/// NULL ---------------- Topology Build Completed -----------------> IDLE
/// IDLE -------------------- sceVoiceStart -----------------------> READY
/// READY ------------ SCEVOICE_EVENT_SERVICE_ATTACHED ------------> BUFFERING
/// BUFFERING ------------ Data reaches threshold ------------------> RUNNING
/// RUNNING ---- SCEVOICE_EVENT_SERVICE_DETACHED/sceVoiceStop ----> IDLE
/// READY ------------------- sceVoiceStop ------------------------> IDLE
/// @endcode
/// @see SceVoiceBasePortInfo
typedef enum SceVoicePortState
{
	SCEVOICE_PORTSTATE_NULL = -1,			/**< The initial port state */
	SCEVOICE_PORTSTATE_IDLE = 0,			/**< The port is idle*/
	SCEVOICE_PORTSTATE_READY = 1,			/**< The port is ready */
	SCEVOICE_PORTSTATE_BUFFERING = 2,		/**< The port is buffering data */
	SCEVOICE_PORTSTATE_RUNNING = 3			/**< The port is running */
} SceVoicePortState;

/// Enumeration for the bit rate for a port.
/// @see SceVoicePortParam, sceVoiceSetBitRate
typedef enum SceVoiceBitRate
{
	SCEVOICE_BITRATE_NULL = -1,				/**< Null bitrate */
	SCEVOICE_BITRATE_3850 = 3850,			/**< Bit rate of 3850 bps */
	SCEVOICE_BITRATE_4650 = 4650,			/**< Bit rate of 4650 bps */
	SCEVOICE_BITRATE_5700 = 5700,			/**< Bit rate of 5700 bps */
	SCEVOICE_BITRATE_7300 = 7300			/**< Bit rate of 7300 bps */
} SceVoiceBitRate;

/// Enumeration for the sampling rate for a port.
/// @see SceVoicePCMFormat, sceVoiceCreatePort
typedef enum SceVoiceSamplingRate
{
	SCEVOICE_SAMPLINGRATE_NULL = -1,		/**< Null sampling rate */
	SCEVOICE_SAMPLINGRATE_16000 = 16000		/**< 16000 sampling rate */
} SceVoiceSamplingRate;


/// Enumeration for the PCM data type.
/// @see SceVoicePCMFormat
typedef enum SceVoicePcmDataType
{
	SCEVOICE_PCM_NULL = -1,					/**< Null datatype. */
	SCEVOICE_PCM_SHORT_LITTLE_ENDIAN = 0	/**< 16-bit Short stored in little-endian format. */
} SceVoicePcmDataType;


/// Enumeration for SceVoice structure version check; for future structure extension.
///
typedef enum SceVoiceVersion
{
	SCEVOICE_VERSION_100 = 100				/**< Version 100 */
} SceVoiceVersion;

/// Enumeration for application type.
typedef enum SceVoiceAppType
{
	SCEVOICE_APPTYPE_GAME = 1 << 29			/**< Game Application */
} SceVoiceAppType;

/// Enumeration for port attributes.
/// Use <c>sceVoiceGetPortAttr()</c> to request user-set values for the attributes.
/// @see sceVoiceGetPortAttr, sceVoiceSetPortAttr
typedef enum SceVoicePortAttr
{
	/// Attribute used to get the active state of an audio input device. This attribute only applies to \ref SCEVOICE_PORTTYPE_IN_DEVICE.
	/// <c>sceVoiceGetPortAttr()</c> returns true when the audio input is active, and it returns false when the audio input port is inactive.
	/// The <c>sceVoiceSetPortAttr()</c> function is not applicable for this attribute.
	SCEVOICE_ATTR_AUDIOINPUT_ACTIVE = 1000
} SceVoicePortAttr;


/// Data structure for the PCM format.
/// @see SceVoicePortParam
typedef struct SceVoicePCMFormat
{
	/// PCM data type.
	SceVoicePcmDataType dataType;
	/// Sampling rate.
	SceVoiceSamplingRate sampleRate;
} SceVoicePCMFormat;

/// Data structure for maximum voice resource support.
/// @see sceVoiceGetResourceInfo
typedef struct SceVoiceResourceInfo
{
	/// Maximum number of \ref SCEVOICE_PORTTYPE_IN_VOICE ports supported
	uint16_t    maxInVoicePort;
	/// Maximum number of \ref SCEVOICE_PORTTYPE_OUT_VOICE ports supported
	uint16_t    maxOutVoicePort;
	/// Maximum number of \ref SCEVOICE_PORTTYPE_IN_DEVICE ports supported
	uint16_t    maxInDevicePort;
	/// Maximum number of \ref SCEVOICE_PORTTYPE_OUT_DEVICE ports supported
	uint16_t    maxOutDevicePort;
	/// Maximum number ports supported
	uint16_t    maxTotalPort;
} SceVoiceResourceInfo;

/// Base port information.
/// This structure holds the topology for the port returned from sceVoiceGetPortInfo().
/// @see sceVoiceGetPortInfo
typedef struct SceVoiceBasePortInfo
{
	/// Port type.
	SceVoicePortType portType;
	/// Port state.
	SceVoicePortState state;
	/// Connected ports.
	uint32_t *pEdge;
	/// When <c><i>portType</i></c> is an OPort: The number of bytes that can be removed from the buffer.
	/// When <c><i>portType</i></c> is an IPort: The number of bytes that can be inserted to the buffer.
	uint32_t numByte;
	/// Unit frame size.
	uint32_t frameSize;
	/// Number of connections.
	uint16_t numEdge;
	/// Reserved.
	uint16_t reserved;
}  SceVoiceBasePortInfo __attribute__ ((aligned(32)));

/// Port parameters. This structure is used to create and update ports.
/// @see sceVoiceCreatePort,  sceVoiceUpdatePort
typedef struct SceVoicePortParam
{
	/// Port type
	SceVoicePortType portType;
	/// Shared buffer threshold (in millisecond).
	/// <c><i>threshold</i></c> is not applicable to a #SCEVOICE_PORTTYPE_IN_DEVICE port or output port.
	/// A rough approximate maximum threshold value for IPort:<br>
	/// For #SCEVOICE_PORTTYPE_IN_VOICE
	/// <ul>
	///  <li>Bitrate  3850: 4000 ms</li>
	///  <li>Bitrate  4560: 3300 ms</li>
	///  <li>Bitrate  5700: 2600 ms</li>
	///  <li>Bitrate  7300: 2000 ms</li>
	/// </ul>
	/// For #SCEVOICE_PORTTYPE_IN_PCMAUDIO
	/// <ul>
	/// <li>16-bit integer: (PCM-buffer-size/512*16) ms</li>
	/// </ul>
	uint16_t threshold;
	/// Indicates whether the port is muted by the application via sceVoiceSetMuteFlag().
	uint16_t bMute;
	/// Provides the port volume, a value of 0 silences the port.
	float volume;
	// Union for SceVoicePortParam
	union
	{
		struct
		{
			SceVoiceBitRate bitrate;	/**< Bit rate for the port */
		} voice;						/**< Voice information data structure */

		struct
		{
			uint32_t bufSize;			/**< Buffer size */
			SceVoicePCMFormat format;	/**< PCM format */
		} pcmaudio;						/**< PCM audio information data structure */

		struct
		{
			uint32_t playerId;			/**< Player ID, set as 0 for now */
		} device;						/**< Device information data structure */
	};									/**< Union for SceVoicePortParam */
} SceVoicePortParam __attribute__ ((aligned(32)));

/// Data structure for voice event data.
/// @see SceVoiceEventCallback
typedef struct SceVoiceEventData
{
	/// Event type for this event data.
	/// @see SceVoiceEventType
	SceVoiceEventType eventType;
	/// Arbitrary user data to pass to <c><i>onEvent</i></c> callback function.
	void *pUserData;
	// Union for SceVoiceEventData
	union
	{
		struct
		{
			/// The number of \ref SCEVOICE_PORTTYPE_OUT_VOICE ports with data ready.
			int16_t	num;
			/// The array of \ref SCEVOICE_PORTTYPE_OUT_VOICE port ID.
			uint16_t pid[SCE_VOICE_MAX_OUT_VOICE_PORT];
		} dataReady;					/**< Voice Data Ready structure */
		struct
		{
			/// A flag that determines whether #SCEVOICE_PORTTYPE_IN_DEVICE is muted by the <c>AudioInput</c> driver.
			bool	bActive;
		} audioInput;					/**< <c>AudioInput</c> status structure */
	} ;									/**< Union for SceVoiceEventData */
} SceVoiceEventData __attribute__ ((aligned(32)));

/// Voice Event Callback Function
/// @param pEvent See SceVoiceEventData.
typedef void (*SceVoiceEventCallback)( SceVoiceEventData* pEvent );

/// Data structure for initializing libvoice.
/// @see sceVoiceInit
typedef struct SceVoiceInitParam
{
	/// Application configuration for Voice Service.
	int32_t appType;
	/// Application registers callback for receiving Voice Events.
	/// Pass NULL to disable the Voice Event service.
	/// Pass a callback function pointer to enable the Voice Event service.
	SceVoiceEventCallback onEvent;
	/// Arbitrary user data to pass to <c><i>onEvent</i></c> callback function
	void *pUserData;
	/// Reserved bytes.
	uint8_t reserved[32 - sizeof(int32_t) * 3];
} SceVoiceInitParam  __attribute__ ((aligned(32)));

/// Start parameters. This structure is used to start the voice service.
/// @see sceVoiceStart
typedef struct SceVoiceStartParam
{
	/// Memory address allocated by the application.
	int32_t container;
	/// Reserved bytes.
	uint8_t reserved[32 - sizeof(int32_t) * 1];
}  SceVoiceStartParam __attribute__ ((aligned(32)));


