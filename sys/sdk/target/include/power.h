/*
 * power.h: the power service's error codes and callback arguments, under Sony's names and with
 * Sony's definitions (SDK Release 03.570.011, target/include/power.h). The kernel takes these; the
 * user library's functions come with the user-mode SDK headers.
 */
#ifndef _SCE_POWER_H
#define _SCE_POWER_H

#include <scetypes.h>

#if !defined(_LANGUAGE_ASSEMBLY)

/* error codes */
#define SCE_POWER_ERROR_INVALID_VALUE		-2144665600	/* 0x802B0000 */
#define SCE_POWER_ERROR_ALREADY_REGISTERD	-2144665599	/* 0x802B0001 */
#define SCE_POWER_ERROR_CALLBACK_NOT_REGISTERD	-2144665598	/* 0x802B0002 */
#define SCE_POWER_ERROR_CANT_SUSPEND		-2144665597	/* 0x802B0003 */
#define SCE_POWER_ERROR_NO_BATTERY		-2144665344	/* 0x802B0100 */
#define SCE_POWER_ERROR_DETECTING		-2144665343	/* 0x802B0101 */

/* the power callback's argument: what changed */
#define SCE_POWER_CALLBACKARG_BATTERYEXIST		0x00000080	/* a battery is present */
#define SCE_POWER_CALLBACKARG_LOWBATTERY		0x00000100
#define SCE_POWER_CALLBACKARG_POWERONLINE		0x00001000	/* external power */
#define SCE_POWER_CALLBACKARG_PROCESS_RESUMING		0x00100000
#define SCE_POWER_CALLBACKARG_PROCESS_RESUME_COMP	0x00200000

/* reserved: no application sees them */
#define SCE_POWER_CALLBACKARG_RESERVED_9		0x00000200
#define SCE_POWER_CALLBACKARG_RESERVED_10		0x00000400
#define SCE_POWER_CALLBACKARG_RESERVED_11		0x00000800
#define SCE_POWER_CALLBACKARG_RESERVED_13		0x00002000
#define SCE_POWER_CALLBACKARG_RESERVED_14		0x00004000
#define SCE_POWER_CALLBACKARG_RESERVED_15		0x00008000
#define SCE_POWER_CALLBACKARG_RESERVED_16		0x00010000
#define SCE_POWER_CALLBACKARG_RESERVED_17		0x00020000
#define SCE_POWER_CALLBACKARG_RESERVED_18		0x00040000
#define SCE_POWER_CALLBACKARG_RESERVED_19		0x00080000
#define SCE_POWER_CALLBACKARG_RESERVED_22		0x00400000
#define SCE_POWER_CALLBACKARG_RESERVED_23		0x00800000
#define SCE_POWER_CALLBACKARG_RESERVED_24		0x01000000
#define SCE_POWER_CALLBACKARG_RESERVED_25		0x02000000
#define SCE_POWER_CALLBACKARG_RESERVED_26		0x04000000
#define SCE_POWER_CALLBACKARG_RESERVED_27		0x08000000
#define SCE_POWER_CALLBACKARG_RESERVED_28		0x10000000
#define SCE_POWER_CALLBACKARG_RESERVED_29		0x20000000
#define SCE_POWER_CALLBACKARG_RESERVED_30		0x40000000
#define SCE_POWER_CALLBACKARG_RESERVED_31		0x80000000

/* scePowerSetConfigurationMode's modes */
#define SCE_POWER_CONFIGURATION_MODE_A	0x00000080U	/* ARM normal, GPU normal, WLAN/COM usable */
#define SCE_POWER_CONFIGURATION_MODE_B	0x00000800U	/* ARM normal, GPU fast, no WLAN/COM */
#define SCE_POWER_CONFIGURATION_MODE_C	0x00010880U	/* ARM normal, GPU fast, WLAN/COM usable, with limits */

#endif /* !_LANGUAGE_ASSEMBLY */

#endif /* _SCE_POWER_H */
