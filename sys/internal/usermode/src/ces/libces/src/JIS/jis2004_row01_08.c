int _sceCesSJis2004Row_1_8_ToUcs4(const SceCesJisUcsProfile *prof, uint8_t ku, uint8_t ten,
				  uint32_t *ucs4)
{
	uint32_t ucs;
	int i;

	i = (ku - 1) * 94 + ten - 1;
	ucs = cesJIS2004Row1To8_UcsTable[i];
	if (ucs == 0) {
		*ucs4 = 0;
		return SCE_CES_ERROR_UNASSIGNED_CODE;
	}
	if (ku <= 2) {
		if (prof->types & CES_JIS_TYPE_CP932) {
			switch (ucs) {
			case 0x2014:			/* EM DASH: HORIZONTAL BAR */
				ucs = 0x2015;
				break;
			case 0x301c:			/* WAVE DASH: FULLWIDTH TILDE */
				ucs = 0xff5e;
				break;
			case 0x2212:			/* MINUS SIGN: FULLWIDTH HYPHEN-MINUS */
				ucs = 0xff0d;
				break;
			case 0x2016:			/* DOUBLE VERTICAL LINE: PARALLEL TO */
				ucs = 0x2225;
				break;
			case 0x00a2:			/* the cent, pound and not signs: fullwidth */
				ucs = 0xffe0;
				break;
			case 0x00a3:
				ucs = 0xffe1;
				break;
			case 0x00ac:
				ucs = 0xffe2;
				break;
			}
		} else if (ucs == 0xff3c) {
			if (prof->types & CES_JIS_TYPE_YEN_BACKSLASH)
				ucs = 0x5c;
		} else if (ucs == 0xff5e) {
			if ((prof->types & CES_JIS_TYPE_TILDE) && prof->jisX0212_to_ucs4 == NULL)
				ucs = 0x7e;
		}
	}
	*ucs4 = ucs;
	return SCE_CES_OK;
}

/* rows 1-8 of JIS X 0208: without JIS X 0213's level 3 additions */
int _sceCesSJisRow_1_8_ToUcs4(const SceCesJisUcsProfile *prof, uint8_t ku, uint8_t ten,
			      uint32_t *ucs4)
{
	if (_sceCesJisRow_1_8_GetLevel(ku, ten) == 1)
		return _sceCesSJis2004Row_1_8_ToUcs4(prof, ku, ten, ucs4);
	*ucs4 = 0;
	return SCE_CES_ERROR_UNASSIGNED_CODE;
}
