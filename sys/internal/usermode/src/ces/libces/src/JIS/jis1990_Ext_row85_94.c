#define IBM_COUNT	(sizeof(cesSJisUcsTbl_IBM_FA40_FC4B) / sizeof(cesSJisUcsTbl_IBM_FA40_FC4B[0]))
/* an IBM extension's UCS code point; 0 past the table */
#define IBM_UCS(n)	((n) < IBM_COUNT ? cesSJisUcsTbl_IBM_FA40_FC4B[n] : 0)

int _sceCesSJisRow_85_94_ToUcs4(const SceCesJisUcsProfile *prof, uint8_t ku, uint8_t ten,
				uint32_t *ucs4)
{
	uint32_t ucs = 0;

	if (ku >= 89 && ku <= 92 && (prof->types & CES_JIS_TYPE_NEC_IBM_EX)) {
		if (ku == 92 && ten > 78) {
			if (ten >= 81) {
				if (ten <= 90)
					ucs = IBM_UCS((uint32_t)(ten - 81));
				else if (ten <= 94)
					ucs = IBM_UCS((uint32_t)(ten - 71));
			}
		} else {
			ucs = IBM_UCS((uint32_t)((ku - 89) * 94 + ten - 1 + 28));
		}
	}
	*ucs4 = ucs;
	if (ucs == 0)
		return SCE_CES_ERROR_UNASSIGNED_CODE;
	return SCE_CES_OK;
}

int _sceCesSJisRow_95_120_ToUcs4(const SceCesJisUcsProfile *prof, uint8_t ku, uint8_t ten,
				 uint32_t *ucs4)
{
	if (ku >= 115) {
		*ucs4 = IBM_UCS((uint32_t)((ku - 115) * 94 + ten - 1));
		if (*ucs4 != 0)
			return SCE_CES_OK;
	}
	*ucs4 = 0;
	return SCE_CES_ERROR_UNASSIGNED_CODE;
}

/* the IBM table's index of a UCS code point; -1 for none */
int _sceCesSJisIBMIndexFromUcs(uint32_t ucs4)
{
	uint32_t n = IBM_COUNT;

	{
		int i;

		for (i = 0; i < n; i++) {
			if (cesSJisUcsTbl_IBM_FA40_FC4B[cesSJisUcsTblIndex_IBM_FA40_FC4B[i]] == ucs4)
				return cesSJisUcsTblIndex_IBM_FA40_FC4B[i];
		}
	}
	return -1;
}
