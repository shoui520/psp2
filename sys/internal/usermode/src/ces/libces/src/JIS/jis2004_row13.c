/*
 * libSceCes's jis2004_row13.c (Sony's internal/usermode/src/ces/libces/src/JIS): plane 1 row 13,
 * JIS X 0213's symbols and NEC's special characters, to UCS.
 */
#include <stddef.h>
#include <stdint.h>
#include <ces/error.h>
#include "ces_jis_profile.h"

/* the UCS code points of row 13 by cell; 0 for none */
static const uint16_t cesJIS2004Row13_UcsTable[94] = {
	/* ku 13 */
	0x2460, 0x2461, 0x2462, 0x2463, 0x2464, 0x2465, 0x2466, 0x2467,
	0x2468, 0x2469, 0x246a, 0x246b, 0x246c, 0x246d, 0x246e, 0x246f,
	0x2470, 0x2471, 0x2472, 0x2473, 0x2160, 0x2161, 0x2162, 0x2163,
	0x2164, 0x2165, 0x2166, 0x2167, 0x2168, 0x2169, 0x216a, 0x3349,
	0x3314, 0x3322, 0x334d, 0x3318, 0x3327, 0x3303, 0x3336, 0x3351,
	0x3357, 0x330d, 0x3326, 0x3323, 0x332b, 0x334a, 0x333b, 0x339c,
	0x339d, 0x339e, 0x338e, 0x338f, 0x33c4, 0x33a1, 0x216b, 0x0000,
	0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x337b, 0x301d,
	0x301f, 0x2116, 0x33cd, 0x2121, 0x32a4, 0x32a5, 0x32a6, 0x32a7,
	0x32a8, 0x3231, 0x3232, 0x3239, 0x337e, 0x337d, 0x337c, 0x0000,
	0x0000, 0x0000, 0x222e, 0x0000, 0x0000, 0x0000, 0x0000, 0x221f,
	0x22bf, 0x0000, 0x0000, 0x0000, 0x2756, 0x261e,
};

int _sceCesSJis2004Row_13_ToUcs4(const SceCesJisUcsProfile *prof, uint8_t ku, uint8_t ten,
				 uint32_t *ucs4)
{
	int i;

	i = (ku - 13) * 94 + ten - 1;
	*ucs4 = cesJIS2004Row13_UcsTable[i];
	if (*ucs4 == 0)
		return SCE_CES_ERROR_UNASSIGNED_CODE;
	return SCE_CES_OK;
}

/* NEC's row 13: JIS X 0213's but for cells 31, 55 and 93-94, NEC's own in cells 80-92 */
int _sceCesSJisNECRow_13_ToUcs4(const SceCesJisUcsProfile *prof, uint8_t ku, uint8_t ten,
				uint32_t *ucs4)
{
	if (ten == 31 || ten == 55 || ten >= 93) {
		*ucs4 = 0;
		return SCE_CES_ERROR_UNASSIGNED_CODE;
	}
	if (ten >= 80) {
		static const uint16_t cesJisNECUniqueUCSTable[13] = {
	0x2252, 0x2261, 0x222b, 0x222e, 0x2211, 0x221a, 0x22a5, 0x2220,
	0x221f, 0x22bf, 0x2235, 0x2229, 0x222a,
		};

		*ucs4 = cesJisNECUniqueUCSTable[ten - 80];
		return SCE_CES_OK;
	}
	return _sceCesSJis2004Row_13_ToUcs4(prof, ku, ten, ucs4);
}
