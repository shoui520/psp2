int _sceCesGB2byte4_ToUcs4(const SceCesGbUcsProfile *prof, uint32_t gbc, uint32_t *ucs4)
{
	uint32_t index;
	uint32_t ucs = 0;

	if (gbc < 0xfe50) {
		index = _sceCesGBGetIndex(gbc);
		ucs = _sceCesIndexUcsDB_getUcs4(cesGBK4_Ucs_DB, CES_INDEX_DB_LAST(cesGBK4_Ucs_DB),
						index);
	} else {
		/* code page 936 has none of them */
		if ((prof->types & (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO)) ==
		    (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO))
			goto set_ucs;
		index = gbc - (gbc > 0xfe7e ? 0xfe51 : 0xfe50);
		if (index >= 80)
			goto set_ucs;
		ucs = cesGB18030_2000_2byte4_fe50_Ucs_Table[index];
	}
	/* the codes GB18030-2000 maps into the PUA */
	if (ucs >= 0xe000 && ucs <= 0xf8ff && (prof->types & CES_GB_TYPES_PUA) == 0)
		ucs = 0;
set_ucs:
	*ucs4 = ucs;
	if (ucs != 0)
		return SCE_CES_OK;
	return SCE_CES_ERROR_UNASSIGNED_CODE;
}

uint32_t _sceCesGBGet2byteSect4Code_FromUcs4(const SceCesGbUcsProfile *prof, uint32_t ucs4)
{
	if (ucs4 >= 0x4e00) {
		int index = _sceCesIndexUcsDB_getIndex(cesGBK4_Ucs_DB,
						       CES_INDEX_DB_LAST(cesGBK4_Ucs_DB), ucs4);

		if (index >= 0)
			return _sceCesGBGetIndexCode(index);
	} else if ((prof->types & (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO)) !=
		   (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO)) {
		const uint16_t *tbl = cesGB18030_2000_2byte4_fe50_Ucs_Table;
		int max = 80;
		int n;

		for (n = 0; n < max; n++, tbl++) {
			if (ucs4 == *tbl) {
				uint32_t gbc = n + 0xfe50;

				if (gbc >= 0xfe7f)
					gbc = n + 0xfe51;
				return gbc;
			}
		}
	}
	return 0;
}
