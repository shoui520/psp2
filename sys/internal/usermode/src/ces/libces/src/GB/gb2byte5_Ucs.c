int _sceCesGB2byte5_ToUcs4(const SceCesGbUcsProfile *gbProf, uint32_t gbc, uint32_t *ucs4)
{
	uint32_t gbc1 = gbc >> 8;
	uint32_t gbc2 = gbc & 0xff;
	uint32_t index;
	uint32_t ucs;

	index = gbc2 < 0x7f ? gbc2 - 0x40 : gbc2 - 0x41;
	if (gbc1 < 0xa8 && (gbProf->types & CES_GB_TYPES_UDA_UCS_PUA) != 0) {
		/* the user-defined area 0xA140-0xA7A0 from U+E4C6 */
		*ucs4 = gbc1 * 96 + index + (0xe4c6 - 0xa1 * 96);
		return SCE_CES_OK;
	}
	index += gbc1 * 96 - 0xa8 * 96;
	/* 0xA989-0xA995, ideographic description characters, are not in code page 936 */
	if (gbc >= 0xa989 && gbc <= 0xa995 && gbProf->types < CES_GB_TYPES_EDITION_2000 &&
	    (gbProf->types & (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO)) ==
		    (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO))
		ucs = 0;
	else if (index < 2 * 96)
		ucs = cesGBK5_Ucs_Table[index];
	else
		ucs = 0;
	/* the codes GB18030-2000 maps into the PUA */
	if (ucs >= 0xe000 && ucs <= 0xf8ff && (gbProf->types & CES_GB_TYPES_PUA) == 0)
		ucs = 0;
	*ucs4 = ucs;
	if (ucs != 0)
		return SCE_CES_OK;
	return SCE_CES_ERROR_UNASSIGNED_CODE;
}
