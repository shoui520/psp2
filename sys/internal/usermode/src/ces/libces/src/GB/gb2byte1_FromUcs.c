uint32_t _sceCesGBGet2byteSect1Code_FromUcs4(const SceCesGbUcsProfile *prof, uint32_t ucs4)
{
	uint16_t dbc;

	/* GB18030-2000 maps U+01F9 to 0xA8BF, GB18030-2005 U+1E3F to 0xA8BC */
	if (ucs4 == 0x01f9 && prof->types >= CES_GB_TYPES_EDITION_2000)
		dbc = 0xa8bf;
	else if (ucs4 == 0x1e3f && prof->types >= CES_GB_TYPES_EDITION_2005)
		dbc = 0xa8bc;
	else
		dbc = _sceCesUcsDbcDB_getDbc(cesGB_UcsGBSect1DB, CES_DB_LAST(cesGB_UcsGBSect1DB),
					     ucs4);
	return dbc;
}
