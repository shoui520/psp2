/* 0xA989-0xA995, the ideographic description characters, which code page 936 does not have */
static const CesUcsDbcDB_t cesGB18030Ex_UcsGBSect5DB[] = {
	{ 0x2ff0, 0xa98a }, { 0x0000, 0xa995 }, { 0x303e, 0xa989 },
};

uint32_t _sceCesGBGet2byteSect5Code_FromUcs4(const SceCesGbUcsProfile *gbProf, uint32_t ucs4)
{
	uint16_t dbc = _sceCesUcsDbcDB_getDbc(cesGB_UcsGBSect5DB,
					      CES_DB_LAST(cesGB_UcsGBSect5DB), ucs4);

	if (dbc == 0 &&
	    (gbProf->types >= CES_GB_TYPES_EDITION_2000 ||
	     (gbProf->types & (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO)) !=
		     (CES_GB_TYPES_CP936 | CES_GB_TYPES_EURO)))
		dbc = _sceCesUcsDbcDB_getDbc(cesGB18030Ex_UcsGBSect5DB,
					     CES_DB_LAST(cesGB18030Ex_UcsGBSect5DB), ucs4);
	return dbc;
}
