static const double huge_rad = 85445659.44705395;	/* 2^27 2/pi: reduce modulo 2pi above it */
static const double invtwopi = 0.15915494309189535;
static const double twobypi = 0.6366197723675814;
static const double pi = 3.141592653589793;
static const double piby4 = 0.7853981633974483;

unsigned int _Quad(double *px)
{
	double x = *px;
	double g;

	if (-huge_rad < x && x < huge_rad) {	/* reduce by pi/2 directly */
		g = x * twobypi;
		g = 0.0 <= g ? g + 0.5 : g - 0.5;
		_Dint(&g, 0);
		if (g != 0.0) {	/* g pi/2 is gs times 2pi 2^26 */
			const double gs = g * 0.25 / 67108864.0;

			x = x - gs * twopi_mod[0][0] - gs * twopi_mod[0][1] - gs * twopi_mod[0][2]
			    - gs * twopi_mod[0][3] - gs * twopi_mod[0][4];
		}
		*px = x;
	} else {	/* reduce modulo 2pi first */
		double t[NTERMS];
		double w[2];
		double acc[NTERMS];
		short yexp;
		short xexp;
		int n;

		g = x;
		_Dunscale(&xexp, &g);
		if (xexp < 86) {
			_Xp_setw(acc, NTERMS, x);
		} else {	/* x 2^(-32k) times 2^(32k) modulo 2pi */
			xexp = (xexp - 54) >> 5;
			_Dscale(&x, -32 * xexp);
			_Xp_setw(w, 2, x);
			memcpy(acc, twopi_mod[xexp], sizeof(acc));
			_Xp_mulh(acc, NTERMS, w[0]);
			if (w[1] != 0.0) {
				memcpy(t, twopi_mod[xexp], sizeof(t));
				_Xp_mulh(t, NTERMS, w[1]);
				_Xp_addx(acc, NTERMS, t, NTERMS);
			}
		}
		for (n = NTERMS; acc[0] < -huge_rad || huge_rad < acc[0];) {	/* subtract multiples of 2pi */
			g = (acc[0] + acc[1]) * invtwopi;
			_Dint(&g, 0);
			_Xp_setw(w, 2, -g / 67108864.0);
			memcpy(t, twopi_mod[0], n * sizeof(double));
			_Xp_mulh(t, n, w[0]);
			if (w[1] != 0.0) {
				double u[NTERMS];
				double y = acc[0];

				_Dunscale(&yexp, &y);
				n = NUSED(yexp) <= NTERMS ? NUSED(yexp) : NTERMS;
				memcpy(u, twopi_mod[0], n * sizeof(double));
				_Xp_mulh(u, n, w[1]);
				_Xp_addx(t, n, u, n);
			}
			_Xp_addx(acc, n, t, n);
		}
		g = (acc[0] + acc[1]) * twobypi;	/* then by pi/2 */
		g = 0.0 <= g ? g + 0.5 : g - 0.5;
		_Dint(&g, 0);
		if (g != 0.0) {
			double v[NTERMS];
			double y = acc[0];

			_Dunscale(&yexp, &y);
			n = NUSED(yexp) <= NTERMS ? NUSED(yexp) : NTERMS;
			memcpy(v, twopi_mod[0], n * sizeof(double));
			_Xp_mulh(v, n, g * -0.25 / 67108864.0);
			_Xp_addx(acc, n, v, n);
		}
		x = _Xp_getw(acc, n);
		*px = x;
	}
	if (g < -(double)INT_MAX || (double)INT_MAX < g)	/* keep the quadrant in an int */
		g = fmod(g, (double)INT_MAX + 1);
	return (int)g & 3;
}

unsigned int _Quadph(double *px, double phase)
{
	unsigned int qoff = _Quad(px);
	double ph = phase;
	double x;

	_Dint(&ph, 1);	/* the multiple of 1/2 in phase */
	phase -= ph;
	if (ph < -(double)(INT_MAX / 2) || (double)(INT_MAX / 2) < ph)
		ph = fmod(ph, (double)(INT_MAX / 2) + 1);
	qoff += (int)(ph * 2.0) & 3;
	x = *px + phase * pi;
	if (piby4 <= x) {
		++qoff;
		x = *px + (phase - 0.5) * pi;
	} else if (x <= -piby4) {
		--qoff;
		x = *px + (phase + 0.5) * pi;
	}
	*px = x;
	return qoff;
}
