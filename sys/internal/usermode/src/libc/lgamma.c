static const double half_ln2pi = 0.41893853320467274;	/* ln(2 pi) / 2 - 1/2 */
static const double ln2hi = 0.6931470632553101;	/* ln 2, high bits */
static const double ln2lo = 1.1730463525082348e-07;	/* ln 2, the rest */
static const double pi = 3.14159265358979323846;

static double stirling(double x)	/* lgamma(x) for x >= _Gamma_big */
{
	const double r = 1.0 / x;
	const double lnxm1 = _Log(x, 0) - 1.0;
	const double g = r * r;
	double y = x - 0.5;
	short xexp;

	_Dunscale(&xexp, &y);
	y *= lnxm1;
	if (_Dscale(&y, xexp) < 0)
		y = ((c[0] * g + c[1]) * g + c[2]) * r + half_ln2pi + y;
	else
		_Feraise(_FE_OVERFLOW);
	return y;
}

double (lgamma)(double x)
{
	double y = x;

	switch (_Dint(&y, 0)) {
	case _NANCODE:
		return x;
	case _INFCODE:
		return _Inf._Double;
	case 0:
		if (x <= 0.0) {	/* a pole at the integers not above zero */
			_Feraise(_FE_DIVBYZERO);
			return _Inf._Double;
		}
		/* fall through */
	default:
		if (x < -_Gamma_big) {	/* the reflection of a large -x */
			const double w = _Log(pi / (x * _Sin((x - y) * pi, 0)), 0);

			return w - stirling(-x);
		} else if (_Gamma_big <= x) {
			return stirling(x);
		} else {
			int i;

			for (i = 0; i < sizeof(zero) / sizeof(zero[0]); ++i)
				if (zero[i].lo < x && x < zero[i].hi)
					break;
			if (i < sizeof(zero) / sizeof(zero[0]))	/* near a zero */
				return _Poly(x - zero[i].zhi - zero[i].zlo, zero[i].tab, zero[i].n);
			if (1.2 < x && x < 1.5) {
				for (i = 0; i < sizeof(range) / sizeof(range[0]); ++i)
					if (x < range[i].xmax)
						break;
				x -= range[i].xoff;
				return _Poly(x, range[i].num, range[i].nnum)
				       / _Poly(x, range[i].den, range[i].nden);
			} else {
				short xexp;
				const double z = _Tgamma(&x, &xexp);
				const double n = -xexp;

				x = -_Log(x < 0.0 ? -x : x, 0) + n * ln2lo + n * ln2hi;
				return x + log1p(z);
			}
		}
	}
}
