static const double xsmall = 0.4769362762044699;	/* erfc(x) is 1 - erf(x) below */

double (erfc)(double x)
{
	switch (_Dtest(&x)) {
	case _NANCODE:
		return x;
	case 0:
		return 1.0;
	case _INFCODE:
		return DSIGN(x) ? 2.0 : 0.0;
	default:
		if (x < xsmall) {
			return 1.0 - erf(x);
		} else if (x < 1.523) {
			double y;

			if (x < x1) {
				y = x - x0;
				return _Poly(y, numa, 8) / _Poly(y, dena, 9);
			} else {
				y = x - x2;
				return _Poly(y, numb, 8) / _Poly(y, denb, 9);
			}
		} else {
			int i;

			for (i = 0; i < sizeof(range) / sizeof(range[0]); ++i) {
				if (x < range[i].xmax) {
					double y = 1.0 / x - range[i].xoff;
					double z;
					double t;

					z = _Poly(y, range[i].num, range[i].nnum)
					    / _Poly(y, range[i].den, range[i].nden);
					t = x;
					_Dint(&t, 17);	/* x^2 = t^2 + (x - t)(x + t) */
					z *= exp((t - x) * (x + t));
					t = -t * t;
					_Exp(&t, z, 0);
					return t;
				}
			}
			_Feraise(_FE_UNDERFLOW);
			return 0.0;
		}
	}
}
