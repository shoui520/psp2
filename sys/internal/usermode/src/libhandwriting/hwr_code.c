int hwrRunStrokeMatchPass(uint16_t strokeCount, uint16_t flags)
{
	uint16_t listIdx = (uint16_t)(strokeCount - 1);
	uint16_t segSum = 0;
	uint16_t idx;
	uint16_t threshold;
	HwrCandidateList *list;
	uint16_t outer;
	uint16_t inner;
	uint16_t keepCount;

	for (idx = 0; idx < (uint16_t)(listIdx + 1); idx++)
		segSum = (uint16_t)(segSum + g_hwrStrokeBuf->strokeSegCount[idx]);

	threshold = g_hwrSegThresholdPtr[(uint16_t)(segSum + listIdx) - 1];
	if ((flags & 2u) != 0)
		hwrPackStrokeFeatures(listIdx);
	else
		threshold = 127u;

	list = &g_hwrStagePtr->lists[listIdx];
	list->items = g_hwrStagePtr->entries[listIdx];
	list->capacity = 16;
	list->count = 0;
	list->maxScore = threshold;
	hwrSetActiveCandList(list);
	hwrMatchAllCoarseModels(flags, 0);

	for (outer = 1; outer < list->count; outer++) {
		HwrCandidate *curCand = &list->items[outer];
		HwrDictCharEntry *curOwner = ((HwrStrokeModel *)curCand->pattern)->ownerChar;

		for (inner = 0; inner < outer; inner++) {
			HwrCandidate *prevCand = &list->items[inner];
			HwrDictCharEntry *prevOwner = ((HwrStrokeModel *)prevCand->pattern)->ownerChar;

			if (curOwner == prevOwner) {
				if (curCand->distance <= prevCand->distance)
					prevCand->distance = threshold;
				else
					curCand->distance = threshold;
			}
		}
	}

	if (list->count > 1)
		hwrSortCandidates(list, 0, (int16_t)(list->count - 1));

	keepCount = 0;
	while (keepCount < list->count) {
		if (list->items[keepCount].distance >= threshold && keepCount >= 2u) {
			list->count = keepCount;
			break;
		}
		keepCount++;
	}
	return list->count;
}

void hwrRelocateDict(void)
{
	uintptr_t delta = (uintptr_t)g_hwrDictBase -
			  ((uintptr_t)g_hwrDictHeader->charTable - 108u);
	HwrCoarseHeader *coarse;
	uint32_t *pool;
	uint16_t idx;
	uint32_t poolPos;
	uint8_t *charCursor;
	uint8_t *modelCursor;

	g_hwrDictHeader->charTable = (HwrDictCharEntry *)((uintptr_t)g_hwrDictBase + 108u);
	g_hwrDictHeader->modelTable = (HwrStrokeModel *)((uintptr_t)g_hwrDictHeader->modelTable + delta);
	g_hwrDictHeader->ruleTable = (void *)((uintptr_t)g_hwrDictHeader->ruleTable + delta);
	g_hwrDictHeader->extraTable = (void *)((uintptr_t)g_hwrDictHeader->extraTable + delta);
	g_hwrDictHeader->coarseHeader = (HwrCoarseHeader *)((uintptr_t)g_hwrDictHeader->coarseHeader + delta);

	coarse = g_hwrDictHeader->coarseHeader;
	coarse->minStrokes = (uint8_t *)((uintptr_t)coarse->minStrokes + delta);
	coarse->featureVectors = (uint8_t *)((uintptr_t)coarse->featureVectors + delta);
	coarse->groupPool = (uint32_t *)((uintptr_t)coarse->groupPool + delta);

	pool = coarse->groupPool;
	poolPos = 0;
	for (idx = 0; idx < coarse->templateCount; idx++) {
		uint32_t count = pool[poolPos++];
		uint32_t sub;

		for (sub = 0; sub < count; sub++) {
			pool[poolPos] += (uint32_t)delta;
			poolPos++;
		}
	}

	for (idx = 0; idx < 4; idx++) {
		if (g_hwrDictHeader->strokeBuckets[idx] != (HwrStrokeModel *)HWR_INVALID_PTR) {
			g_hwrDictHeader->strokeBuckets[idx] =
				(HwrStrokeModel *)((uintptr_t)g_hwrDictHeader->strokeBuckets[idx] + delta);
		}
	}

	charCursor = (uint8_t *)g_hwrDictHeader->charTable;
	for (idx = 0; idx < g_hwrDictHeader->charCount; idx++) {
		HwrDictCharEntry *entry = (HwrDictCharEntry *)charCursor;

		if (entry->firstModel != (HwrStrokeModel *)HWR_INVALID_PTR)
			entry->firstModel = (HwrStrokeModel *)((uintptr_t)entry->firstModel + delta);
		if (entry->splitDirMask != 0) {
			entry->leftRadical = (HwrDictCharEntry *)((uintptr_t)entry->leftRadical + delta);
			entry->rightRadical = (HwrDictCharEntry *)((uintptr_t)entry->rightRadical + delta);
		}
		charCursor += 24u + 4u * entry->extraCount;
	}

	modelCursor = (uint8_t *)g_hwrDictHeader->modelTable;
	for (idx = 0; idx < g_hwrDictHeader->modelCount; idx++) {
		HwrStrokeModel *model = (HwrStrokeModel *)modelCursor;

		model->ownerChar = (HwrDictCharEntry *)((uintptr_t)model->ownerChar + delta);
		if (model->nextByChar != (HwrStrokeModel *)HWR_INVALID_PTR)
			model->nextByChar = (HwrStrokeModel *)((uintptr_t)model->nextByChar + delta);
		if (model->nextByBucket != (HwrStrokeModel *)HWR_INVALID_PTR)
			model->nextByBucket = (HwrStrokeModel *)((uintptr_t)model->nextByBucket + delta);
		model->ruleBytecode = (uint8_t *)((uintptr_t)model->ruleBytecode + delta);
		modelCursor += model->recordSize;
	}
}

