int hwrOctagonalDistance(int16_t xStart, int16_t yStart, int16_t xEnd, int16_t yEnd)
{
	uint16_t dx = (xEnd > xStart) ? (uint16_t)(xEnd - xStart) : (uint16_t)(xStart - xEnd);
	uint16_t dy = (yEnd > yStart) ? (uint16_t)(yEnd - yStart) : (uint16_t)(yStart - yEnd);

	if (dx >= dy)
		return (uint16_t)(dx + (dy >> 1) + 1);
	return (uint16_t)(dy + (dx >> 1) + 1);
}

int hwrDescrambleLicenseKey(char *dst, const char *src, int len)
{
	HwrKeyChunkDesc passFirst[5];
	HwrKeyChunkDesc passSecond[5];
	HwrKeyChunkDesc *passes[3];
	uint8_t chunkA[4];
	uint8_t chunkB[4];
	uint8_t chunkC[4];
	uint8_t chunkD[4];
	uint8_t chunkE[4];
	uint8_t chunkF[4];
	uint8_t chunkG[4];
	uint8_t chunkH[4];
	int passIdx;

	hwrMemcpy(passFirst, s_keyPassFirstInit, sizeof(passFirst));
	passFirst[0].key = chunkB;
	passFirst[1].key = chunkA;
	passFirst[2].key = chunkD;
	passFirst[3].key = chunkC;

	hwrMemcpy(passSecond, s_keyPassSecondInit, sizeof(passSecond));
	passSecond[0].key = chunkH;
	passSecond[1].key = chunkE;
	passSecond[2].key = chunkF;
	passSecond[3].key = chunkG;

	passes[0] = passFirst;
	passes[1] = passSecond;
	passes[2] = NULL;

	chunkA[0] = 0xA7u; chunkA[1] = 0x4Cu; chunkA[2] = 0xE7u; chunkA[3] = 0x50u;
	chunkB[0] = 0xFCu; chunkB[1] = 0x64u; chunkB[2] = 0x41u; chunkB[3] = 0x6Bu;
	chunkC[0] = 0xB9u; chunkC[1] = 0xBAu; chunkC[2] = 0x99u; chunkC[3] = 0x91u;
	chunkD[0] = 0x93u; chunkD[1] = 0xA1u; chunkD[2] = 0x62u; chunkD[3] = 0x3Du;
	chunkE[0] = 0xF4u; chunkE[1] = 0xBFu; chunkE[2] = 0x20u; chunkE[3] = 0x47u;
	chunkF[0] = 0x3Du; chunkF[1] = 0x85u; chunkF[2] = 0x4Fu; chunkF[3] = 0x48u;
	chunkG[0] = 0x9Eu; chunkG[1] = 0xF8u; chunkG[2] = 0xA0u; chunkG[3] = 0xE2u;
	chunkH[0] = 0x31u; chunkH[1] = 0x87u; chunkH[2] = 0xBCu; chunkH[3] = 0x40u;

	if (len != 17)
		return -1;

	for (passIdx = 0; passes[passIdx] != NULL; passIdx++) {
		const HwrKeyChunkDesc *desc = passes[passIdx];

		while (desc->key != NULL) {
			int off = desc->offset;
			int byteIdx;

			if (desc->reverse != 0) {
				for (byteIdx = 3; byteIdx >= 0; byteIdx--) {
					uint8_t keyByte = desc->key[byteIdx];
					int pos = off + byteIdx;

					if (passIdx != 0)
						dst[pos] ^= (char)keyByte;
					else
						dst[pos] = (char)(keyByte ^ (uint8_t)src[pos]);
				}
			} else {
				for (byteIdx = 0; byteIdx < 4; byteIdx++) {
					uint8_t keyByte = desc->key[byteIdx];
					int pos = off + byteIdx;

					if (passIdx != 0)
						dst[pos] ^= (char)keyByte;
					else
						dst[pos] = (char)(keyByte ^ (uint8_t)src[pos]);
				}
			}
			desc++;
		}
	}
	dst[16] = '\0';
	return 0;
}

int hwrVerifyLicenseKey(void)
{
	char decoded[20];

	hwrDescrambleLicenseKey(decoded, g_hwrLicenseKeyBuf, 17);
	if (hwrStrcmp(g_hwrLicenseKeyExpected, decoded) == 0)
		return 0;
	return -1;
}

int hwrVerifyAuth(void)
{
	if (hwrVerifyLicenseKey() != 0)
		return -105;
	if (hwrVerifyVersionSignature() != 0)
		return -1;
	return 0;
}

uint32_t hwrInternalToUnicode(uint16_t internalCode)
{
	uint32_t result = 0;

	if (internalCode < 0xE800u || internalCode > 0xF8FFu)
		return internalCode;
	if (internalCode >= 0xE800u && internalCode <= 0xEFFFu) {
		const HwrUnicodeMapEntry *entry = s_unicodeLowMap;

		while (entry->internalCode != 0xFFFFu) {
			if (entry->internalCode == internalCode) {
				result = entry->unicode;
				break;
			}
			entry++;
		}
	} else if (internalCode >= 0xF000u && internalCode <= 0xF8FFu) {
		const HwrUnicodeMapEntry *entry = s_unicodeHighMap;

		while (entry->internalCode != 0xFFFFu) {
			if (entry->internalCode == internalCode) {
				result = entry->unicode;
				break;
			}
			entry++;
		}
	}
	return result;
}

uint16_t hwrUnicodeToInternal(uint32_t unicode)
{
	uint16_t result = 0;

	if ((unicode & 0xFFFF0000u) == 0) {
		if (unicode >= 0x20u && (unicode <= 0xE7FFu || unicode >= 0xF900u) &&
		    unicode <= 0xFFFDu) {
			return (uint16_t)unicode;
		}
		return result;
	}

	{
		const HwrUnicodeMapEntry *entry = s_unicodeLowMap;

		while (entry->internalCode != 0xFFFFu) {
			if (entry->unicode == unicode) {
				result = entry->internalCode;
				break;
			}
			entry++;
		}
	}
	if (result != 0)
		return result;

	{
		const HwrUnicodeMapEntry *entry = s_unicodeHighMap;

		while (entry->internalCode != 0xFFFFu) {
			if (entry->unicode == unicode) {
				result = entry->internalCode;
				break;
			}
			entry++;
		}
	}
	return result;
}

