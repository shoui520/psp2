int hwrFeedStrokePoints(const uint8_t *pointBytes)
{
	uint16_t offset = 0;

	if (pointBytes == NULL)
		return -1;
	if (hwrSessionBegin() == -1)
		return -1;

	while (!(pointBytes[offset] == 255u && pointBytes[offset + 1] == 255u)) {
		uint16_t count = 0;
		uint8_t curByte = pointBytes[offset];

		if (offset >= 2046u) {
			hwrSessionEnd();
			return -1;
		}
		if ((curByte & 0x80u) == 0) {
			offset += 2;
			continue;
		}
		while ((curByte & 0x80u) != 0) {
			uint8_t xCoord;
			uint8_t yCoord;

			if (curByte == 255u && pointBytes[offset + 1] == 255u) {
				hwrSessionEnd();
				return -1;
			}
			xCoord = curByte & 0x7Fu;
			yCoord = pointBytes[(uint16_t)(offset + 1)];
			if (yCoord >= 0x80u)
				yCoord = 127u;
			g_hwrRawStrokeBuf.points[count].x = xCoord;
			g_hwrRawStrokeBuf.points[count].y = yCoord;
			offset += 2;
			curByte = pointBytes[offset];
			if (count > 0 &&
			    xCoord == g_hwrRawStrokeBuf.points[count - 1].x &&
			    yCoord == g_hwrRawStrokeBuf.points[count - 1].y)
				count--;
			if (count >= 255u)
				count--;
			count++;
		}
		if (count != 0) {
			uint8_t lastX = curByte & 0x7Fu;
			uint8_t lastY;

			offset++;
			lastY = pointBytes[offset];
			if (lastY >= 0x80u)
				lastY = 127u;
			g_hwrRawStrokeBuf.points[count].x = lastX;
			g_hwrRawStrokeBuf.points[count].y = lastY;
			g_hwrRawStrokeBuf.pointCount = (uint16_t)(count + 1);
			offset++;
			if (hwrSessionAddStroke(&g_hwrRawStrokeBuf, 0) == -1) {
				hwrSessionEnd();
				return -1;
			}
		} else {
			offset += 2;
		}
	}
	return 0;
}

int hwrEngineRecognize(HwrWorkBuffer *workBuf)
{
	uint16_t tempCodes[HWR_MAX_CANDIDATES];
	uint16_t tempScores[HWR_MAX_CANDIDATES];
	uint8_t localPoints[2048];
	int count;
	uint16_t idx;

	hwrResetUserResults();
	if (workBuf == NULL)
		return -1;
	hwrMemcpyFast(localPoints, workBuf->pointBytes, sizeof(localPoints));
	if (hwrFeedStrokePoints(localPoints) == -1) {
		hwrResetUserResults();
		return -1;
	}
	count = hwrSessionRecognize(g_hwrRecogResults, HWR_MAX_CANDIDATES, 0);
	if (count != -1) {
		for (idx = 0; idx < count; idx++) {
			tempScores[idx] = g_hwrRecogResults[idx].distance;
			tempCodes[idx] = g_hwrRecogResults[idx].code;
		}
	}
	if (hwrSessionEnd() == -1 || count == -1) {
		hwrResetUserResults();
		return -1;
	}
	for (idx = 0; idx < count; idx++) {
		workBuf->scores[idx] = tempScores[idx];
		workBuf->codes[idx] = hwrInternalToUnicode(tempCodes[idx]);
	}
	return count;
}

uint16_t hwrBuildCategoryMask(uint16_t mode)
{
	unsigned int mask = 0x8000u;

	if (mode & SCE_HANDWRITING_MODE_NUMBER)
		mask |= 0x0002u;
	if (mode & SCE_HANDWRITING_MODE_UALPHA)
		mask |= 0x0004u;
	if (mode & SCE_HANDWRITING_MODE_LALPHA)
		mask |= 0x0008u;
	if (mode & SCE_HANDWRITING_MODE_SYMBOL)
		mask |= 0x0001u;
	if (mode & SCE_HANDWRITING_MODE_HIRA)
		mask |= 0x0010u;
	if (mode & SCE_HANDWRITING_MODE_KATA)
		mask |= 0x0020u;
	if (mode & SCE_HANDWRITING_MODE_GREEK)
		mask |= 0x0044u;
	if (mode & SCE_HANDWRITING_MODE_HANGUL)
		mask |= 0x0080u;
	if (mode & SCE_HANDWRITING_MODE_HANJA)
		mask |= 0x0100u;
	if (mode & 0x0200u)
		mask |= 0x0200u;
	if (mode & SCE_HANDWRITING_MODE_KANJI1)
		mask |= 0x0400u;
	if (mode & SCE_HANDWRITING_MODE_KANJI2)
		mask |= 0x0800u;
	if ((mode & SCE_HANDWRITING_MODE_ALL) == SCE_HANDWRITING_MODE_ALL)
		mask |= SCE_HANDWRITING_MODE_ALL;
	return (uint16_t)mask;
}

