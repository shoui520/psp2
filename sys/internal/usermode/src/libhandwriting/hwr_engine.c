int hwrPackStrokeFeatures(uint16_t lastStrokeIdx)
{
	uint16_t totalSegs = 0;
	uint16_t strokeIdx;
	uint16_t strokeLimit = (uint16_t)(lastStrokeIdx + 1);
	uint16_t segIdx;
	uint16_t totalPacked;
	uint16_t curStroke = 1;

	for (strokeIdx = 0; strokeIdx < strokeLimit; strokeIdx++)
		totalSegs = (uint16_t)(totalSegs + g_hwrStrokeBuf->strokeSegCount[strokeIdx]);

	g_hwrPackedFeat.strokeStartSeg[0] = 0;
	totalPacked = (uint16_t)(totalSegs + lastStrokeIdx);

	for (segIdx = 0; segIdx < totalPacked; segIdx++) {
		const HwrSegment *seg = &g_hwrStrokeBuf->segments[segIdx];
		uint8_t packed = g_hwrPackedFeat.segments[segIdx];

		packed = (uint8_t)((packed & 0x8Fu) | ((seg->normLength & 7u) << 4));
		packed = (uint8_t)((packed & 0xF0u) | (seg->direction & 0x0Fu));
		packed = (uint8_t)((packed & 0x7Fu) | ((seg->penDown & 1u) << 7));
		g_hwrPackedFeat.segments[segIdx] = packed;
		if ((seg->penDown & 1u) == 0) {
			g_hwrPackedFeat.strokeEndSeg[curStroke - 1] = (uint16_t)(segIdx - 1);
			g_hwrPackedFeat.strokeStartSeg[curStroke] = (uint16_t)(segIdx + 1);
			curStroke++;
		}
	}

	g_hwrPackedFeat.segCount = totalPacked;
	g_hwrPackedFeat.segPtr = g_hwrPackedFeat.segments;
	g_hwrPackedFeat.strokeEndSeg[curStroke - 1] = (uint16_t)(totalPacked - 1);
	g_hwrPackedFeat.startStroke = 0;
	g_hwrPackedFeat.strokeCount = strokeLimit;
	g_hwrPackedFeat.firstSeg = 0;
	g_hwrPackedFeat.lastSeg = (uint16_t)(totalPacked - 1);
	return (int)totalPacked - 1;
}

void hwrSetActiveCandList(HwrCandidateList *list)
{
	g_hwrActiveCandList = list;
}

unsigned int hwrDpMatch(HwrDpAlignment *align, const uint8_t *modelSegs,
			uint16_t modelSegCount, uint16_t maxCost)
{
	uint16_t rowCost[65];
	const uint8_t *inputSegs = g_hwrPackedFeat.segPtr;
	uint16_t inputLen = g_hwrPackedFeat.segCount;
	uint8_t *pathPtr = g_hwrDpPathBuf;
	uint16_t colLeft = 0;
	uint16_t colRight = 0;
	uint16_t bestCol = 255;
	uint16_t rowMin = 255;
	uint16_t beamWidth = 12;
	uint16_t col;
	uint16_t row;
	uint16_t finalCost;
	int baseDir;

	g_hwrDpMatchCallCount++;
	baseDir = 16 - (modelSegs[0] & 0x0F);

	for (col = 0; col < inputLen; col++) {
		int16_t cost = g_hwrDirCostPtr[((inputSegs[col] & 0x0F) + baseDir) & 0x0F];

		if (col == 0) {
			rowCost[0] = (uint16_t)cost;
			rowMin = rowCost[0];
			*pathPtr++ = 3;
		} else {
			uint16_t acc = (uint16_t)(rowCost[col - 1] + cost);

			rowCost[col] = acc;
			colRight = (uint16_t)(col - 1);
			if (modelSegCount != 1 && (int)(rowMin + beamWidth) < (int)acc) {
				pathPtr += (inputLen - col);
				break;
			}
			*pathPtr++ = 3;
		}
		beamWidth = (uint16_t)(beamWidth + 6);
	}

	if (modelSegCount > 1) {
		for (row = 1; row < modelSegCount; row++) {
			int curBaseDir = 16 - (modelSegs[row] & 0x0F);
			uint16_t diagPrev = 255;
			uint16_t leftPrev = 255;
			uint16_t curMin = 255;
			uint16_t curBeam = 12;
			uint16_t scanCol;
			uint16_t pruneLimit = g_hwrDpPrunePtr[row];

			pathPtr += colLeft;
			for (col = colLeft; col <= colRight; col++) {
				uint16_t dirCost = (uint16_t)g_hwrDirCostPtr[
					(curBaseDir + (inputSegs[col] & 0x0F)) & 0x0F];
				uint16_t upCost = rowCost[col];
				uint16_t bestVal;
				uint8_t move;

				if (diagPrev > upCost) {
					if (leftPrev >= upCost) {
						bestVal = (uint16_t)(dirCost + upCost);
						move = 2;
					} else {
						bestVal = (uint16_t)(dirCost + leftPrev);
						move = 3;
					}
				} else if (leftPrev >= diagPrev) {
					bestVal = (uint16_t)(dirCost + diagPrev);
					move = 1;
				} else {
					bestVal = (uint16_t)(dirCost + leftPrev);
					move = 3;
				}
				rowCost[col] = bestVal;
				*pathPtr++ = move;
				if (bestVal < curMin) {
					curMin = bestVal;
					bestCol = col;
				}
				diagPrev = upCost;
				leftPrev = bestVal;
			}

			for (col = (uint16_t)(colRight + 1); col < inputLen; col++) {
				uint16_t dirCost = (uint16_t)g_hwrDirCostPtr[
					(curBaseDir + (inputSegs[col] & 0x0F)) & 0x0F];
				uint8_t *curPath = pathPtr;
				uint16_t bestVal;
				uint8_t move;

				if (leftPrev >= diagPrev) {
					bestVal = (uint16_t)(dirCost + diagPrev);
					move = 1;
				} else {
					bestVal = (uint16_t)(dirCost + leftPrev);
					curBeam = (uint16_t)(curBeam + 6);
					move = 3;
				}
				rowCost[col] = bestVal;
				*pathPtr++ = move;
				if (bestVal < curMin) {
					curMin = bestVal;
					bestCol = col;
				} else if ((int)(curMin + curBeam) < (int16_t)bestVal) {
					colRight = (uint16_t)(col - 1);
					if (row == (uint16_t)(modelSegCount - 1))
						return 255u;
					rowCost[col] = 255u;
					pathPtr = curPath + (inputLen - col);
					break;
				}
				leftPrev = bestVal;
				diagPrev = 255u;
				colRight = col;
			}

			for (scanCol = colLeft; scanCol < bestCol; scanCol++) {
				if ((unsigned int)(curMin + curBeam) > rowCost[scanCol]) {
					colLeft = scanCol;
					break;
				}
			}
			if (pruneLimit < curMin)
				return 255u;
		}
	}

	finalCost = rowCost[inputLen - 1];
	if (finalCost >= maxCost)
		return 255u;
	if (finalCost < 127u && (((unsigned int)inputSegs[0] >> 4) & 7u) < 3u) {
		int diffIdx = ((inputSegs[0] & 0x0F) - (modelSegs[0] & 0x0F) + 16) & 0x0F;

		finalCost = (uint16_t)(finalCost - g_hwrFirstSegDiscountPtr[diffIdx]);
	}

	{
		int16_t curRow = (int16_t)(modelSegCount - 1);
		int16_t curCol = (int16_t)(inputLen - 1);
		uint8_t *trace = &g_hwrDpPathBuf[(int16_t)inputLen * (int16_t)modelSegCount - 1];

		align->startSeg[modelSegCount] = inputLen;
		while (trace != g_hwrDpPathBuf) {
			align->startSeg[(uint16_t)curRow] = (uint16_t)curCol;
			if (*trace == 1) {
				curRow--;
				curCol--;
				trace -= (inputLen + 1);
			} else if (*trace == 2) {
				curRow--;
				trace -= inputLen;
			} else if (*trace == 3) {
				curCol--;
				trace--;
			}
		}
		align->startSeg[(uint16_t)curRow] = (uint16_t)curCol;
	}

	for (row = 0; row < modelSegCount; row++) {
		uint16_t segStart = align->startSeg[row];
		uint16_t segEnd = align->startSeg[row + 1];

		if (segStart == segEnd) {
			align->mainSeg[row] = segStart;
			align->endSeg[row] = segStart;
		} else {
			int bestWeight = 0;
			uint16_t pos;

			for (pos = segStart; pos < segEnd; pos++) {
				int weight = (int)(((unsigned int)inputSegs[pos] >> 4) & 7u) + 1;

				align->endSeg[row] = pos;
				if (weight > bestWeight) {
					bestWeight = weight;
					align->mainSeg[row] = pos;
				}
			}
		}
	}
	return finalCost;
}

void hwrMatchAllCoarseModels(uint16_t flags, uint16_t mode)
{
	int16_t minX, minY, maxX, maxY;
	uint16_t idx;

	(void)flags;
	hwrGetStrokeRangeBBox(g_hwrPackedFeat.startStroke, g_hwrPackedFeat.strokeCount,
			      &minX, &minY, &maxX, &maxY);
	for (idx = 0; idx < g_hwrCoarseCharCount; idx++) {
		HwrDictCharEntry *charEntry = g_hwrCoarseCharPtrs[idx];

		if (charEntry == (HwrDictCharEntry *)0xFFFFu)
			continue;
		HwrStrokeModel *model = charEntry->firstModel;

		while (model != (HwrStrokeModel *)HWR_INVALID_PTR) {
			int extraTol = 0;
			int minStrokeAdj = g_hwrPackedFeat.strokeCount;

			if (charEntry != model->ownerChar)
				break;
			if (model->strictStrokeCount == 0) {
				extraTol = g_hwrCfg.extraStrokeTol;
				minStrokeAdj = g_hwrPackedFeat.strokeCount + g_hwrCfg.missingStrokeTol;
			}
			if (model->minStrokes <= minStrokeAdj &&
			    model->maxStrokes + extraTol >= g_hwrPackedFeat.strokeCount) {
				const uint8_t *rules = model->ruleBytecode;

				if (rules[0] <= (uint8_t)g_hwrPackedFeat.segCount &&
				    rules[1] >= (uint8_t)g_hwrPackedFeat.segCount) {
					int dpScore = (int)hwrDpMatch(&g_hwrDpAlign,
								      model->segments,
								      model->segmentCount,
								      127u);

					if (dpScore != 255 &&
					    dpScore < (int)g_hwrActiveCandList->maxScore) {
						uint16_t totalScore = (uint16_t)(dpScore +
							hwrEvaluateRules(model->ruleBytecode,
									 g_hwrPackedFeat.startStroke,
									 g_hwrPackedFeat.strokeCount,
									 0, 0));

						if (totalScore < g_hwrActiveCandList->maxScore) {
							hwrInsertCandidate(g_hwrActiveCandList,
									   model, totalScore,
									   g_hwrPackedFeat.startStroke,
									   g_hwrPackedFeat.strokeCount,
									   0, (int16_t)mode);
						}
					}
				}
			}
			model = model->nextByChar;
		}
	}
}
