static __attribute__((always_inline)) inline uint8_t hwrUserEntryChecksum(const HwrUserEntry *entry)
{
	const uint8_t *bytes = (const uint8_t *)entry;
	uint8_t sum = 0;
	int idx;

	for (idx = 0; idx < 512; idx += 4) {
		sum = (uint8_t)(sum + bytes[idx] + bytes[idx + 1] +
				bytes[idx + 2] + bytes[idx + 3]);
	}
	return (uint8_t)(sum - entry->checksum);
}

int hwrUserRegInit(uint16_t capacity, HwrUserEntry *regBuf)
{
	int idx;

	if (regBuf == NULL || capacity == 0 || capacity > SCE_HANDWRITING_MAX_REGISTER_COUNT)
		return -1;
	if (g_hwrCfg.engineState == 0 || g_hwrUserRegBuf != NULL)
		return -1;
	g_hwrUserRegBuf = regBuf;
	g_hwrUserRegCapacity = capacity;
	hwrResetUserResults();
	for (idx = 0; idx < capacity; idx++) {
		if (hwrUserEntryChecksum(&g_hwrUserRegBuf[idx]) !=
		    g_hwrUserRegBuf[idx].checksum) {
			g_hwrUserRegBuf = NULL;
			g_hwrUserRegCapacity = 0;
			return -301;
		}
	}
	return 0;
}

