#!/usr/bin/env python3
"""
Wrap a radio controller's 8051 program (SDCC's Intel hex output) in the form
the ARM firmware loads it: its length (16 bits, little-endian), the code from
the load address, then the 16-bit sum of the length and code bytes, which the
controller's loader checks.

    radioimage.py OUT IHX BASE

OUT is a C initializer (comma-separated bytes) for the array that holds the
image (wlanPacketBufferPoolMemory, btPoolHeaderMemory). BASE is the program's
load address: the code before it (the 8051 vectors at 0) is not loaded.
"""
import sys


def read_ihx(path):
    memory = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line.startswith(':'):
                continue
            record = bytes.fromhex(line[1:])
            count, address, kind = record[0], (record[1] << 8) | record[2], record[3]
            if sum(record) & 0xff:
                sys.exit('%s: bad checksum: %s' % (path, line))
            if kind == 0:
                for i in range(count):
                    memory[address + i] = record[4 + i]
            elif kind == 1:
                break
    return memory


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    out, ihx, base = sys.argv[1], sys.argv[2], int(sys.argv[3], 0)
    memory = read_ihx(ihx)
    if min(memory) < base:
        sys.exit('%s: code at 0x%x, below the load address 0x%x' % (ihx, min(memory), base))
    end = max(memory) + 1
    code = bytes(memory.get(a, 0) for a in range(base, end))
    if len(code) & 1:
        code += b'\0'
    image = len(code).to_bytes(2, 'little') + code
    image += (sum(image) & 0xffff).to_bytes(2, 'little')
    with open(out, 'w') as f:
        f.write('/* Generated by radio/radioimage.py from %s. */\n' % ihx.rsplit('/', 1)[-1])
        for i in range(0, len(image), 16):
            f.write(' '.join('0x%02x,' % b for b in image[i:i + 16]) + '\n')


if __name__ == '__main__':
    main()
