/* sum of the products, the even terms and the odd ones in two saturating accumulators */
static int32_t dotProduct(const int32_t *x, const int32_t *row)
{
	int64_t even = 0, odd = 0;
	int32_t k;

	for (k = 0; k < HALF; k += 2) {
		even = ivc2AddWide(even, ivc2Product(x[k], row[k]));
		odd = ivc2AddWide(odd, ivc2Product(x[k + 1], row[k + 1]));
	}
	return ivc2High(even + odd);
}

/* 0x8e9710: the sums and differences are also left in x, the differences reversed */
static void matrix(int32_t *x, int32_t *v)
{
	int32_t sums[HALF], differences[HALF], k, m;

	for (k = 0; k < HALF; k++) {
		sums[k] = ivc2AddSaturate(x[k], x[SUBBANDS - 1 - k]);
		differences[k] = ivc2SubtractSaturate(x[k], x[SUBBANDS - 1 - k]);
	}
	for (k = 0; k < HALF; k++) {
		x[k] = sums[k];
		x[SUBBANDS - 1 - k] = differences[k];
	}
	for (m = 0; m < HALF; m++) {
		v[2 * m] = dotProduct(sums, matrixSums + HALF * m);
		v[2 * m + 1] = dotProduct(differences, matrixDifferences + HALF * m);
	}
}

/*
 * 0x8e9a10: the 32 samples of a slot from V, eight 64-word groups each read
 * up from A_i = 16 + 64i and down from B_i = 48 + 64i, the even and odd
 * terms in two saturating accumulators. Samples 0-15 are their difference;
 * 16 is minus the odd terms of row 8; 17-31 are minus their sum, the
 * coefficients half a row on (the kernel's CPPERM0/2 pairs, CPERM0 =
 * 0xba983210, CPERM2 = 0xfedc7654).
 */
#define GROUPS		8
#define GROUP_UP(i)	(16 + 64 * (i))
#define GROUP_DOWN(i)	(48 + 64 * (i))

static int64_t lane(int64_t acc, int32_t v, int32_t d, int32_t subtract)
{
	return subtract ? ivc2SubtractWide(acc, ivc2Product(v, d)) :
		ivc2AddWide(acc, ivc2Product(v, d));
}

void mp3PolyphaseWindow(const int32_t *v, int32_t *output)
{
	int32_t n, i;

	for (n = 0; n < 8; n++) {
		const int32_t *d = windowTable + 32 * n, *e = d + 16;
		int64_t low0 = 0, low1 = 0, high0 = 0, high1 = 0;

		for (i = 0; i < GROUPS; i++) {
			low0 = lane(low0, v[GROUP_UP(i) + 2 * n], d[2 * i], 0);
			low1 = lane(low1, v[GROUP_DOWN(i) - 2 * n], d[2 * i + 1], 0);
			high0 = lane(high0, v[GROUP_UP(i) + 2 * n + 1], e[2 * i], 0);
			high1 = lane(high1, v[GROUP_DOWN(i) - 2 * n - 1], e[2 * i + 1], 0);
		}
		output[2 * n] = ivc2High(low0 - low1);
		output[2 * n + 1] = ivc2High(high0 - high1);
	}

	{
		int64_t middle = 0;

		for (i = 0; i < GROUPS; i++)
			middle = lane(middle, v[GROUP_UP(i) + 16], windowTable[256 + 2 * i + 1], 1);
		output[16] = ivc2High(middle);
	}

	for (n = 0; n < 8; n++) {
		const int32_t *d = windowTable + 272 + 32 * n, *e = d + 16;
		int64_t low0 = 0, low1 = 0, high0 = 0, high1 = 0;

		for (i = 0; i < GROUPS; i++) {
			low0 = lane(low0, v[GROUP_DOWN(i) - 17 - 2 * n], d[2 * i], 1);
			low1 = lane(low1, v[GROUP_UP(i) + 17 + 2 * n], d[2 * i + 1], 1);
			if (n < 7) {
				high0 = lane(high0, v[GROUP_DOWN(i) - 18 - 2 * n], e[2 * i], 1);
				high1 = lane(high1, v[GROUP_UP(i) + 18 + 2 * n], e[2 * i + 1], 1);
			}
		}
		output[17 + 2 * n] = ivc2High(low0 + low1);
		if (n < 7)
			output[18 + 2 * n] = ivc2High(high0 + high1);
	}
}

static void copyWords(int32_t *to, const int32_t *from, int32_t count)
{
	while (count--)
		*to++ = *from++;
}

/* 0x8ea068 */
void mp3Polyphase(int32_t *xr, int32_t *work, int32_t *polyphase, uint32_t offset)
{
	int32_t slot;

	for (slot = 0; slot < SLOTS; slot++, xr += SUBBANDS) {
		if (offset == 288)
			copyWords(work + 288, polyphase, HISTORY);
		offset -= SUBBANDS;
		matrix(xr, work + offset);
		mp3PolyphaseWindow(work + offset, xr);
		if (offset == 0) {
			copyWords(polyphase, work, HISTORY);
			offset = 288;
		}
	}
}
