/* the sum over `count` terms, even and odd ones in two saturating accumulators */
static int64_t dotProduct(const int32_t *x, const int32_t *row, int32_t count)
{
	int64_t even = 0, odd = 0;
	int32_t k;

	for (k = 0; k < count; k += 2) {
		even = ivc2AddWide(even, ivc2Product(x[k], row[k]));
		odd = ivc2AddWide(odd, ivc2Product(x[k + 1], row[k + 1]));
	}
	return even + odd;
}

/* the 64-bit negation's high word, not the negated high word */
static int32_t negatedHigh(int64_t value)
{
	return ivc2High((int64_t)(0 - (uint64_t)value));
}

/*
 * 0x8ea688: the 18 lines (shifted down 2) through the 36-point IMDCT, or
 * the three 12-point ones of a short block (window w from lines 3j + w),
 * windowed, and for a short block overlapped within the 36 outputs.
 */
void mp3ImdctBlock(const int32_t *lines, int32_t *output, uint32_t blockType)
{
	int32_t x[LINES], n, w, i;

	for (i = 0; i < LINES; i++)
		x[i] = lines[i] >> 2;

	if (blockType != MP3_BLOCK_SHORT) {
		for (n = 0; n < 9; n++) {
			int64_t first = dotProduct(x, longFirst[n], LINES);
			int32_t second = ivc2High(dotProduct(x, longSecond[n], LINES));

			output[n] = ivc2High(first);
			output[17 - n] = negatedHigh(first);
			output[18 + n] = second;
			output[35 - n] = second;
		}
	} else {
		for (w = 0; w < 3; w++) {
			int32_t window[6], *out = output + 12 * w;

			for (i = 0; i < 6; i++)
				window[i] = x[3 * i + w];
			for (n = 0; n < 3; n++) {
				int64_t first = dotProduct(window, shortRows[n], 6);
				int32_t second = ivc2High(dotProduct(window, shortRows[3 + n], 6));

				out[n] = ivc2High(first);
				out[5 - n] = negatedHigh(first);
				out[6 + n] = second;
				out[11 - n] = second;
			}
		}
	}

	for (i = 0; i < 36; i++)
		output[i] = (int32_t)(ivc2Product(output[i], windows[blockType][i]) >> 31);

	if (blockType == MP3_BLOCK_SHORT) {
		/* the windows at 6, 12 and 18, overlapping by half */
		for (i = 0; i < 6; i++) {
			int32_t first = output[i], last = output[30 + i];
			uint32_t middle = (uint32_t)output[6 + i] + (uint32_t)output[12 + i];
			uint32_t late = (uint32_t)output[18 + i] + (uint32_t)output[24 + i];

			output[i] = 0;
			output[30 + i] = 0;
			output[6 + i] = first;
			output[12 + i] = (int32_t)middle;
			output[18 + i] = (int32_t)late;
			output[24 + i] = last;
		}
	}
}

void mp3Imdct(int32_t *work, int32_t *xr, int32_t *overlap, uint32_t blockType,
	int32_t *imdctWork, uint32_t longBands)
{
	uint32_t sb, i;

	for (sb = 0; sb < SUBBANDS; sb++, overlap += LINES) {
		mp3ImdctBlock(work + LINES * sb, imdctWork, sb < longBands ? 0 : blockType);
		for (i = 0; i < LINES; i++) {
			xr[SUBBANDS * i + sb] = (int32_t)((uint32_t)imdctWork[i] + (uint32_t)overlap[i]);
			overlap[i] = imdctWork[LINES + i];
		}
	}
	for (i = 1; i < LINES; i += 2)
		for (sb = 1; sb < SUBBANDS; sb += 2)
			xr[SUBBANDS * i + sb] = (int32_t)(0u - (uint32_t)xr[SUBBANDS * i + sb]);
}
