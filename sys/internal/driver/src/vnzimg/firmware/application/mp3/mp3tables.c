/*
 * A Huffman entry: the code left-aligned in the high bits, its length in
 * bits 8-12, x in bits 4-7 and y (or the count1 quadruple) in bits 0-3.
 * A table's entries are sorted by code.
 */
#define HUFF(code, length, x, y) \
	(((uint32_t)(code) << ((32 - (length)) & 31)) | ((length) << 8) | ((x) << 4) | (y))

