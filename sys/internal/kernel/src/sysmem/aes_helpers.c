uint32_t AesSubWord(uint32_t word)
{
	uint32_t high = s_aesSbox[word >> 24];
	uint32_t middleHigh = s_aesSbox[(word >> 16) & 0xff];
	uint32_t middleLow = s_aesSbox[(word >> 8) & 0xff];
	uint32_t low = s_aesSbox[word & 0xff];

	return high << 24 | middleHigh << 16 | middleLow << 8 | low;
}

uint32_t AesInverseMixColumn(uint32_t column)
{
	/* The inverse-matrix rows multiply the four little-endian bytes:
	 * 0e,0b,0d,09; 09,0e,0b,0d; 0d,09,0e,0b; 0b,0d,09,0e.
	 */
	poly8x8_t input = vreinterpret_p8_u32(vdup_n_u32(column));
	poly8x8_t rows01 = vreinterpret_p8_u64(vcreate_u64(0x0d0b0e09090d0b0eULL));
	poly8x8_t rows23 = vreinterpret_p8_u16(vrev32_u16(vreinterpret_u16_p8(rows01)));
	uint32x4_t product01 = vreinterpretq_u32_p16(vmull_p8(input, rows01));
	uint32x4_t product23 = vreinterpretq_u32_p16(vmull_p8(input, rows23));
	uint32x4x2_t pairs = vuzpq_u32(product01, product23);
	uint16x8_t pairsFolded = vreinterpretq_u16_u32(veorq_u32(pairs.val[0], pairs.val[1]));
	uint16x4x2_t halves = vuzp_u16(vget_low_u16(pairsFolded), vget_high_u16(pairsFolded));
	uint16x4_t sums = veor_u16(halves.val[0], halves.val[1]);
	uint16x8_t duplicated = vcombine_u16(sums, sums);
	uint8x8_t low = vmovn_u16(duplicated);
	poly8x8_t high = vreinterpret_p8_u8(vshrn_n_u16(duplicated, 8));
	poly8x8_t reduction = vmul_p8(high, vreinterpret_p8_u8(vdup_n_u8(0x1b)));

	/* Reduce modulo x^8+x^4+x^3+x+1, the original's polynomial 0x11b. */
	return vget_lane_u32(vreinterpret_u32_u8(veor_u8(low, vreinterpret_u8_p8(reduction))), 0);
}
